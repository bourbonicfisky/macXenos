#!/usr/bin/env python3

"""Generate Xenia's build identity header from the current Git worktree."""

import argparse
import os
from pathlib import Path
import subprocess


def _git_output(source_root: Path, *args: str) -> str:
    return subprocess.run(
        ["git", *args],
        cwd=source_root,
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
    ).stdout.strip()


def _build_identity(source_root: Path) -> tuple[str, str, str]:
    try:
        if _git_output(source_root, "rev-parse", "--is-inside-work-tree") != "true":
            raise subprocess.CalledProcessError(1, "git rev-parse")
        try:
            branch = _git_output(
                source_root, "symbolic-ref", "--short", "-q", "HEAD"
            )
        except subprocess.CalledProcessError:
            branch = "detached"
        commit = _git_output(source_root, "rev-parse", "HEAD") or "unknown"
        commit_short = _git_output(source_root, "rev-parse", "--short", "HEAD")
        return branch, commit, commit_short or "unknown"
    except (FileNotFoundError, subprocess.CalledProcessError):
        return "tarball", ":(-dont-do-this", ":("


# Public releases are tagged macxenos-<version> (macxenos-1.0); the public
# export (export_public.sh) carries those tags. Internal builds are tagged
# internal-<version> (internal-1.0.1-test1): versioned the same way, never
# exported.
TAG_PREFIXES = ("macxenos-", "internal-")


def release_version(source_root: Path, commit: str = "HEAD") -> tuple[str, bool]:
    """The version of `commit` and whether it is a release.

    A commit carrying a release or internal tag is that version ("1.0",
    True). A later commit is a development build of the newest tagged
    version before it, with the number of commits since ("1.0+3", False).
    MACXENOS_VERSION overrides both (a test build: "1.0-beta9-test6"), as a
    release only if it has no "+".
    """
    override = os.getenv("MACXENOS_VERSION", "").strip()
    if override:
        return override, "+" not in override and "-dev" not in override
    try:
        matches = [arg for prefix in TAG_PREFIXES
                   for arg in ("--match", prefix + "*")]
        described = _git_output(
            source_root, "describe", "--tags", "--long", *matches, commit
        )
    except (FileNotFoundError, subprocess.CalledProcessError):
        return "dev", False
    # <prefix><version>-<commits since>-g<hash>; the version may contain "-".
    tag, since, _ = described.rsplit("-", 2)
    version = next(tag[len(prefix):] for prefix in TAG_PREFIXES
                   if tag.startswith(prefix))
    if since == "0":
        return version, True
    return f"{version}+{since}", False


def generate_version_header(source_root: Path, output: Path) -> None:
    branch, commit, commit_short = _build_identity(source_root)
    version, is_release = release_version(source_root)
    contents = f"""// Autogenerated by tools/build/generate_version_header.py.
#ifndef GENERATED_VERSION_H_
#define GENERATED_VERSION_H_
#define XE_BUILD_BRANCH "{branch}"
#define XE_BUILD_COMMIT "{commit}"
#define XE_BUILD_COMMIT_SHORT "{commit_short}"
#define XE_BUILD_DATE __DATE__
#define XE_BUILD_VERSION "{version}"
"""
    if is_release:
        contents += "#define XE_BUILD_IS_RELEASE\n"

    github_ref = os.getenv("GITHUB_REF", "")
    if os.getenv("GITHUB_EVENT_NAME") == "pull_request" and github_ref.startswith(
        "refs/pull/"
    ):
        contents += "#define XE_BUILD_IS_PR\n"
        contents += f'#define XE_BUILD_PR_NUMBER "{github_ref.split("/")[2]}"\n'

    contents += "#endif  // GENERATED_VERSION_H_\n"
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text() == contents:
        return
    output.write_text(contents)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--output", type=Path)
    parser.add_argument(
        "--print-version",
        metavar="COMMIT",
        nargs="?",
        const="HEAD",
        help="print the version of COMMIT (default HEAD) and whether it is a "
        "release (release|development), then exit",
    )
    args = parser.parse_args()
    if args.print_version:
        version, is_release = release_version(
            args.source_root.resolve(), args.print_version
        )
        print(version, "release" if is_release else "development")
        return
    if not args.output:
        parser.error("--output is required")
    generate_version_header(args.source_root.resolve(), args.output.resolve())


if __name__ == "__main__":
    main()
