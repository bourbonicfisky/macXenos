#!/usr/bin/env python3

"""Generate Xenia's build identity header from the current Git worktree."""

import argparse
import os
from pathlib import Path
import subprocess


def _git_output(source_root: Path, *args: str) -> str:
    return subprocess.run(
        ["git", *args],
        cwd=source_root,
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
    ).stdout.strip()


def _build_identity(source_root: Path) -> tuple[str, str, str]:
    try:
        if _git_output(source_root, "rev-parse", "--is-inside-work-tree") != "true":
            raise subprocess.CalledProcessError(1, "git rev-parse")
        try:
            branch = _git_output(
                source_root, "symbolic-ref", "--short", "-q", "HEAD"
            )
        except subprocess.CalledProcessError:
            branch = "detached"
        commit = _git_output(source_root, "rev-parse", "HEAD") or "unknown"
        commit_short = _git_output(source_root, "rev-parse", "--short", "HEAD")
        return branch, commit, commit_short or "unknown"
    except (FileNotFoundError, subprocess.CalledProcessError):
        return "tarball", ":(-dont-do-this", ":("


def generate_version_header(source_root: Path, output: Path) -> None:
    branch, commit, commit_short = _build_identity(source_root)
    contents = f"""// Autogenerated by tools/build/generate_version_header.py.
#ifndef GENERATED_VERSION_H_
#define GENERATED_VERSION_H_
#define XE_BUILD_BRANCH "{branch}"
#define XE_BUILD_COMMIT "{commit}"
#define XE_BUILD_COMMIT_SHORT "{commit_short}"
#define XE_BUILD_DATE __DATE__
"""

    github_ref = os.getenv("GITHUB_REF", "")
    if os.getenv("GITHUB_EVENT_NAME") == "pull_request" and github_ref.startswith(
        "refs/pull/"
    ):
        contents += "#define XE_BUILD_IS_PR\n"
        contents += f'#define XE_BUILD_PR_NUMBER "{github_ref.split("/")[2]}"\n'

    contents += "#endif  // GENERATED_VERSION_H_\n"
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text() == contents:
        return
    output.write_text(contents)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    generate_version_header(args.source_root.resolve(), args.output.resolve())


if __name__ == "__main__":
    main()
