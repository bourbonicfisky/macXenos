#ifndef XENIA_GPU_METAL_METAL_LOAD_SHADER_PIPELINES_H_
#define XENIA_GPU_METAL_METAL_LOAD_SHADER_PIPELINES_H_

#include <cstddef>
#include <cstdint>
#include <vector>

namespace xe {
namespace gpu {
namespace metal {

// Narrowly-owned infrastructure for the offline-compiled texture-load compute
// shaders (the shared cross-backend texture_load_*.cs.xesl sources, MSL
// branch, embedded as generated bytecode/metal/*.h headers): creates the
// MTLLibrary / entry_xe MTLFunction / MTLComputePipelineState set and owns
// their lifetime. This component makes NO texture-routing decision — nothing
// in the emulator texture-fetch path consumes it yet; consumers arrive with
// the separately-gated shadow route (OpenSpec gpu-texture-loads slices 3+).
class MetalLoadShaderPipelines {
 public:
  struct ShaderInfo {
    // Identifier from the generated header, e.g. "texture_load_32bpb_cs".
    const char* name;
    const uint8_t* metallib;
    size_t metallib_size;
  };

  // Threadgroup shape shared by every texture-load shader
  // (LOCAL_SIZE_*_XE in texture_load.xesli). MSL leaves the threadgroup
  // shape to the dispatch site, so the host owns it — always dispatch these
  // pipelines with this shape.
  static constexpr uint32_t kThreadgroupSizeX = 4;
  static constexpr uint32_t kThreadgroupSizeY = 32;
  static constexpr uint32_t kThreadgroupSizeZ = 1;

  // Buffer binding indices of the entry_xe ABI (texture_load.xesli).
  static constexpr uint32_t kBufferIndexPushConstants = 0;
  static constexpr uint32_t kBufferIndexDest = 1;
  static constexpr uint32_t kBufferIndexSource = 2;

  // Host mirror of the MSL push_const_struct_xe for the texture-load family
  // (texture_load.xesli) — the ONE packing definition every dispatcher and
  // test must use. MSL uint3 is 16-byte aligned AND 16-byte sized, so
  // xe_texture_load_host_offset lands at offset 32, not 28 (verified on
  // device by the slice-2 dispatch conformance).
  struct LoadConstants {
    uint32_t is_tiled_3d_endian_scale;           // 0
    uint32_t guest_offset;                       // 4
    uint32_t guest_pitch_aligned;                // 8
    uint32_t guest_z_stride_block_rows_aligned;  // 12
    uint32_t size_blocks[3];                     // 16
    uint32_t pad_uint3_w;                        // 28 (uint3 padding)
    uint32_t host_offset;                        // 32
    uint32_t host_pitch;                         // 36
    uint32_t height_texels;                      // 40
    uint32_t pad_tail;                           // 44 (struct align 16)
  };
  static_assert(sizeof(LoadConstants) == 48, "MSL push-const ABI");

  // The full compiled texture-load family, in stable (sorted) order.
  static const ShaderInfo* shaders(size_t* count_out);

  // C1T-R: the direct-to-tiled RGBA8 variant (texture_load_32bpb_direct) is
  // not part of the family table above (it writes a texture, not the linear
  // dest buffer); this builds just its pipeline for the shared-subclass
  // route so load-shader pipeline creation keeps a single owner. Returns a
  // RETAINED id<MTLComputePipelineState> as void* (caller releases), or
  // nullptr on any failure. Dispatch with the same threadgroup shape and
  // push-constant/source bindings as the family; the dest binds at
  // texture(1).
  static void* CreateDirectRgba8Pipeline(void* device);

  MetalLoadShaderPipelines() = default;
  ~MetalLoadShaderPipelines();
  MetalLoadShaderPipelines(const MetalLoadShaderPipelines&) = delete;
  MetalLoadShaderPipelines& operator=(const MetalLoadShaderPipelines&) =
      delete;

  // Builds a library + entry_xe function + compute pipeline for every shader
  // in the family. device is an id<MTLDevice>. Returns false (and leaves the
  // object empty) if any library, function or pipeline cannot be created.
  bool Initialize(void* device);
  void Shutdown();

  bool initialized() const { return !pipelines_.empty(); }
  size_t count() const { return pipelines_.size(); }
  // id<MTLComputePipelineState> as void*; nullptr if out of range or not
  // initialized.
  void* pipeline(size_t index) const {
    return index < pipelines_.size() ? pipelines_[index] : nullptr;
  }
  // Index into shaders()/pipeline() by identifier; -1 if unknown.
  int FindIndex(const char* name) const;

 private:
  // Retained id<MTLComputePipelineState> handles, same order as shaders().
  std::vector<void*> pipelines_;
};

}  // namespace metal
}  // namespace gpu
}  // namespace xe

#endif  // XENIA_GPU_METAL_METAL_LOAD_SHADER_PIPELINES_H_
