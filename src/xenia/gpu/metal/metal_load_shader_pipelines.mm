MetalLoadShaderPipelines::~MetalLoadShaderPipelines() { Shutdown(); }

bool MetalLoadShaderPipelines::Initialize(void* device) {
  Shutdown();
  if (!device) {
    return false;
  }
  id<MTLDevice> mtl_device = (__bridge id<MTLDevice>)device;
  size_t count;
  const ShaderInfo* infos = shaders(&count);
  std::vector<void*> pipelines;
  pipelines.reserve(count);
  bool ok = true;
  for (size_t i = 0; i < count && ok; ++i) {
    const ShaderInfo& info = infos[i];
    // Wrap the embedded bytes without copying; they are static storage, so
    // the no-op destructor is safe.
    dispatch_data_t data = dispatch_data_create(
        info.metallib, info.metallib_size, nullptr,
        ^{
        });
    NSError* error = nil;
    id<MTLLibrary> library = [mtl_device newLibraryWithData:data
                                                      error:&error];
#if !__has_feature(objc_arc)
    dispatch_release(data);
#endif
    if (!library) {
      XELOGE("MetalLoadShaderPipelines: newLibraryWithData failed for {}: {}",
             info.name,
             error ? [[error localizedDescription] UTF8String] : "unknown");
      ok = false;
      break;
    }
    // The XeSL MSL entry point is always entry_xe; resolve it by name rather
    // than trusting function order.
    id<MTLFunction> function = [library newFunctionWithName:@"entry_xe"];
    if (!function) {
      XELOGE("MetalLoadShaderPipelines: no entry_xe in {}", info.name);
#if !__has_feature(objc_arc)
      [library release];
#endif
      ok = false;
      break;
    }
    error = nil;
    id<MTLComputePipelineState> pipeline =
        [mtl_device newComputePipelineStateWithFunction:function error:&error];
#if !__has_feature(objc_arc)
    [function release];
    [library release];
#endif
    if (!pipeline) {
      XELOGE("MetalLoadShaderPipelines: pipeline creation failed for {}: {}",
             info.name,
             error ? [[error localizedDescription] UTF8String] : "unknown");
      ok = false;
      break;
    }
    pipelines.push_back((__bridge_retained void*)pipeline);
  }
  if (!ok) {
    for (void* p : pipelines) {
      id<MTLComputePipelineState> pipeline =
          (__bridge_transfer id<MTLComputePipelineState>)p;
      (void)pipeline;
    }
    return false;
  }
  pipelines_ = std::move(pipelines);
  return true;
}

void MetalLoadShaderPipelines::Shutdown() {
  for (void* p : pipelines_) {
    id<MTLComputePipelineState> pipeline =
        (__bridge_transfer id<MTLComputePipelineState>)p;
    (void)pipeline;
  }
  pipelines_.clear();
}

void* MetalLoadShaderPipelines::CreateDirectRgba8Pipeline(void* device) {
  if (!device) {
    return nullptr;
  }
  id<MTLDevice> mtl_device = (__bridge id<MTLDevice>)device;
  dispatch_data_t data = dispatch_data_create(
      texture_load_32bpb_direct_cs_metallib,
      sizeof(texture_load_32bpb_direct_cs_metallib), nullptr,
      ^{
      });
  NSError* error = nil;
  id<MTLLibrary> library = [mtl_device newLibraryWithData:data error:&error];
#if !__has_feature(objc_arc)
  dispatch_release(data);
#endif
  if (!library) {
    XELOGE(
        "MetalLoadShaderPipelines: newLibraryWithData failed for "
        "texture_load_32bpb_direct: {}",
        error ? [[error localizedDescription] UTF8String] : "unknown");
    return nullptr;
  }
  id<MTLFunction> function = [library newFunctionWithName:@"entry_xe"];
  if (!function) {
    XELOGE("MetalLoadShaderPipelines: no entry_xe in texture_load_32bpb_direct");
#if !__has_feature(objc_arc)
    [library release];
#endif
    return nullptr;
  }
  error = nil;
  id<MTLComputePipelineState> pipeline =
      [mtl_device newComputePipelineStateWithFunction:function error:&error];
#if !__has_feature(objc_arc)
  [function release];
  [library release];
#endif
  if (!pipeline) {
    XELOGE(
        "MetalLoadShaderPipelines: pipeline creation failed for "
        "texture_load_32bpb_direct: {}",
        error ? [[error localizedDescription] UTF8String] : "unknown");
    return nullptr;
  }
  return (__bridge_retained void*)pipeline;
}

int MetalLoadShaderPipelines::FindIndex(const char* name) const {
  size_t count;
  const ShaderInfo* infos = shaders(&count);
  for (size_t i = 0; i < count; ++i) {
    if (!std::strcmp(infos[i].name, name)) {
      return int(i);
    }
  }
  return -1;
}

