using metal::MetalLoadShaderPipelines;
using LoadConstants = MetalLoadShaderPipelines::LoadConstants;
constexpr uint32_t kRowAlign = 256;

struct DirectHarness {
  id<MTLDevice> device = nil;
  id<MTLCommandQueue> queue = nil;
  MetalLoadShaderPipelines pipelines;  // buffer 32bpb (existing family).
  id<MTLComputePipelineState> direct = nil;  // the C1T direct variant.
  int buffer_index = -1;
  bool ok = false;

  DirectHarness() {
    device = MTLCreateSystemDefaultDevice();
    if (!device) {
      return;
    }
    queue = [device newCommandQueue];
    if (!queue || !pipelines.Initialize((__bridge void*)device)) {
      return;
    }
    buffer_index = pipelines.FindIndex("texture_load_32bpb_cs");
    // Build the direct-variant pipeline from the generated metallib.
    dispatch_data_t data = dispatch_data_create(
        texture_load_32bpb_direct_cs_metallib,
        sizeof(texture_load_32bpb_direct_cs_metallib),
        dispatch_get_main_queue(), DISPATCH_DATA_DESTRUCTOR_DEFAULT);
    NSError* err = nil;
    id<MTLLibrary> lib = [device newLibraryWithData:data error:&err];
    if (lib) {
      id<MTLFunction> fn = [lib newFunctionWithName:@"entry_xe"];
      if (fn) {
        direct = [device newComputePipelineStateWithFunction:fn error:&err];
      }
    }
    ok = pipelines.initialized() && buffer_index >= 0 && direct != nil;
  }
};

DirectHarness& H() {
  static DirectHarness h;
  return h;
}

#define REQUIRE_DEVICE()                                        \
  do {                                                          \
    if (!H().device) {                                          \
      FAIL("No Metal device: these cases must run on the M4."); \
    }                                                           \
  } while (0)

struct GuestImage {
  std::vector<uint8_t> tiled;     // guest-layout source bytes.
  std::vector<uint8_t> expected;  // CPU-oracle linear rows at host_pitch.
  uint32_t width, height, pitch_aligned, host_pitch;
};

// The exact end (exclusive) of the guest byte range the direct shader reads.
// Each thread handles 8 texels along X starting at a multiple of 8, so the X
// read set is the PADDED width round_up(width, 8); the shader reads two 16-byte
// (uint4) groups per thread. The read set must be covered by the source
// allocation or the shader reads out of bounds on odd widths (e.g. 47 -> the
// thread at x=40 reads the group covering texels 44..47, i.e. Tiled2D(44, y)
// bytes, even though texel 47 is never STORED). We bound it over every 4-block
// group start Tiled2D(gx, y) + 16 for gx in {0,4,..,padded-4}, all y.
uint32_t DirectShaderReadEnd(uint32_t width, uint32_t height,
                             uint32_t pitch_aligned) {
  uint32_t padded_w = (width + 7u) & ~7u;
  int32_t max_off = 0;
  for (uint32_t y = 0; y < height; ++y) {
    for (uint32_t gx = 0; gx < padded_w; gx += 4) {
      max_off = std::max(max_off, texture_address::Tiled2D(int32_t(gx),
                                                           int32_t(y),
                                                           int32_t(pitch_aligned),
                                                           2));
    }
  }
  return uint32_t(max_off) + 16u;  // + one uint4 (16 bytes) read.
}

GuestImage MakeGuestImage(uint32_t width, uint32_t height,
                          xenos::Endian endian) {
  GuestImage img;
  img.width = width;
  img.height = height;
  img.pitch_aligned = (width + 31u) & ~31u;
  img.host_pitch = ((width * 4u) + (kRowAlign - 1)) & ~(kRowAlign - 1);
  // Size the source over the PADDED read set the shader actually touches, not
  // just the [0,width) stored texels.
  uint32_t read_end = DirectShaderReadEnd(width, height, img.pitch_aligned);
  img.tiled.resize(read_end);
  for (size_t i = 0; i < img.tiled.size(); ++i) {
    img.tiled[i] = uint8_t(i * 5 + (i >> 7) * 11 + 3);
  }
  img.expected.assign(size_t(img.host_pitch) * height, 0);
  for (uint32_t y = 0; y < height; ++y) {
    for (uint32_t x = 0; x < width; ++x) {
      int32_t off = texture_address::Tiled2D(int32_t(x), int32_t(y),
                                             img.pitch_aligned, 2);
      uint32_t word;
      std::memcpy(&word, &img.tiled[off], 4);
      word = xenos::GpuSwap(word, endian);
      std::memcpy(&img.expected[size_t(y) * img.host_pitch + x * 4u], &word, 4);
    }
  }
  return img;
}

LoadConstants MakeConstants(const GuestImage& img, xenos::Endian endian,
                            uint32_t host_offset) {
  LoadConstants c = {};
  c.is_tiled_3d_endian_scale = 1u | (uint32_t(endian) << 2);
  c.guest_offset = 0;
  c.guest_pitch_aligned = img.pitch_aligned;
  c.size_blocks[0] = img.width;
  c.size_blocks[1] = img.height;
  c.size_blocks[2] = 1;
  c.host_offset = host_offset;
  c.host_pitch = img.host_pitch;
  c.height_texels = img.height;
  return c;
}

// Reads an RGBA8Unorm texture's texels back into a tightly-packed w*h*4 buffer
// via a compute read kernel (cross-encoder, same command buffer, no CPU wait
// between the producing dispatch and this read).
id<MTLComputePipelineState> ReadKernel(id<MTLDevice> device) {
  static id<MTLComputePipelineState> ps = nil;
  if (ps) return ps;
  NSString* src = @R"MSL(
    #include <metal_stdlib>
    using namespace metal;
    kernel void read_texels(texture2d<float, access::read> tex [[texture(0)]],
                            device uchar4* out [[buffer(0)]],
                            constant uint2& dims [[buffer(1)]],
                            uint2 gid [[thread_position_in_grid]]) {
      if (gid.x >= dims.x || gid.y >= dims.y) return;
      out[gid.y * dims.x + gid.x] = uchar4(round(tex.read(gid) * 255.0f));
    })MSL";
  NSError* e = nil;
  id<MTLLibrary> lib = [device newLibraryWithSource:src options:nil error:&e];
  id<MTLFunction> fn = [lib newFunctionWithName:@"read_texels"];
  ps = [device newComputePipelineStateWithFunction:fn error:&e];
  return ps;
}

// Samples an RGBA8Unorm texture with a LINEAR sampler at a list of normalized
// coordinates and writes the raw float4 results — the real filtered path a
// consuming draw uses, not raw texel reads.
id<MTLComputePipelineState> SampleKernel(id<MTLDevice> device) {
  static id<MTLComputePipelineState> ps = nil;
  if (ps) return ps;
  NSString* src = @R"MSL(
    #include <metal_stdlib>
    using namespace metal;
    kernel void sample_coords(texture2d<float, access::sample> tex
                                  [[texture(0)]],
                              device const float2* coords [[buffer(0)]],
                              device float4* out [[buffer(1)]],
                              constant uint& n [[buffer(2)]],
                              uint i [[thread_position_in_grid]]) {
      if (i >= n) return;
      constexpr sampler s(coord::normalized, address::clamp_to_edge,
                          filter::linear);
      out[i] = tex.sample(s, coords[i]);
    })MSL";
  NSError* e = nil;
  id<MTLLibrary> lib = [device newLibraryWithSource:src options:nil error:&e];
  id<MTLFunction> fn = [lib newFunctionWithName:@"sample_coords"];
  ps = [device newComputePipelineStateWithFunction:fn error:&e];
  return ps;
}

id<MTLTexture> MakeTexture(id<MTLDevice> device, uint32_t w, uint32_t h,
                           bool writable) {
  MTLTextureDescriptor* d = [MTLTextureDescriptor
      texture2DDescriptorWithPixelFormat:MTLPixelFormatRGBA8Unorm
                                   width:w
                                  height:h
                               mipmapped:NO];
  d.storageMode = MTLStorageModePrivate;
  d.usage = writable ? (MTLTextureUsageShaderRead | MTLTextureUsageShaderWrite)
                     : MTLTextureUsageShaderRead;
  return [device newTextureWithDescriptor:d];
}

// DIRECT path: dispatch the variant to write `tex` directly, then read it
// back — one command buffer, no CPU wait.
std::vector<uint8_t> RunDirect(const GuestImage& img, xenos::Endian endian) {
  auto& h = H();
  id<MTLBuffer> source =
      [h.device newBufferWithBytes:img.tiled.data()
                            length:img.tiled.size()
                           options:MTLResourceStorageModeShared];
  id<MTLTexture> tex = MakeTexture(h.device, img.width, img.height, true);
  uint32_t texel_bytes = img.width * img.height * 4u;
  id<MTLBuffer> out = [h.device newBufferWithLength:texel_bytes
                                            options:MTLResourceStorageModeShared];
  uint32_t dims[2] = {img.width, img.height};
  LoadConstants c = MakeConstants(img, endian, 0);
  id<MTLCommandBuffer> cmd = [h.queue commandBuffer];
  {
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:h.direct];
    [enc setBytes:&c length:sizeof(c) atIndex:0];
    [enc setTexture:tex atIndex:1];
    [enc setBuffer:source offset:0 atIndex:2];
    MTLSize grp = MTLSizeMake(MetalLoadShaderPipelines::kThreadgroupSizeX,
                              MetalLoadShaderPipelines::kThreadgroupSizeY, 1);
    uint32_t tx = (img.width + 7u) / 8u;
    [enc dispatchThreadgroups:MTLSizeMake((tx + grp.width - 1) / grp.width,
                                          (img.height + grp.height - 1) /
                                              grp.height,
                                          1)
        threadsPerThreadgroup:grp];
    [enc endEncoding];
  }
  {
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:ReadKernel(h.device)];
    [enc setTexture:tex atIndex:0];
    [enc setBuffer:out offset:0 atIndex:0];
    [enc setBytes:dims length:sizeof(dims) atIndex:1];
    [enc dispatchThreadgroups:MTLSizeMake((img.width + 7) / 8,
                                          (img.height + 7) / 8, 1)
        threadsPerThreadgroup:MTLSizeMake(8, 8, 1)];
    [enc endEncoding];
  }
  [cmd commit];
  [cmd waitUntilCompleted];
  if (cmd.status != MTLCommandBufferStatusCompleted) return {};
  return std::vector<uint8_t>(static_cast<uint8_t*>(out.contents),
                              static_cast<uint8_t*>(out.contents) + texel_bytes);
}

// BUFFER+BLIT path (the existing shape): load 32bpb into a linear buffer,
// blit to the texture, read back.
std::vector<uint8_t> RunBufferBlit(const GuestImage& img, xenos::Endian endian) {
  auto& h = H();
  id<MTLBuffer> source =
      [h.device newBufferWithBytes:img.tiled.data()
                            length:img.tiled.size()
                           options:MTLResourceStorageModeShared];
  uint32_t linear_size = img.host_pitch * img.height;
  id<MTLBuffer> linear = [h.device newBufferWithLength:linear_size
                                              options:MTLResourceStorageModePrivate];
  id<MTLTexture> tex = MakeTexture(h.device, img.width, img.height, false);
  uint32_t texel_bytes = img.width * img.height * 4u;
  id<MTLBuffer> out = [h.device newBufferWithLength:texel_bytes
                                            options:MTLResourceStorageModeShared];
  uint32_t dims[2] = {img.width, img.height};
  LoadConstants c = MakeConstants(img, endian, 0);
  id<MTLCommandBuffer> cmd = [h.queue commandBuffer];
  {
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:(__bridge id<MTLComputePipelineState>)
                                     h.pipelines.pipeline(size_t(h.buffer_index))];
    [enc setBytes:&c length:sizeof(c) atIndex:0];
    [enc setBuffer:linear offset:0 atIndex:1];
    [enc setBuffer:source offset:0 atIndex:2];
    MTLSize grp = MTLSizeMake(MetalLoadShaderPipelines::kThreadgroupSizeX,
                              MetalLoadShaderPipelines::kThreadgroupSizeY, 1);
    uint32_t tx = (img.width + 7u) / 8u;
    [enc dispatchThreadgroups:MTLSizeMake((tx + grp.width - 1) / grp.width,
                                          (img.height + grp.height - 1) /
                                              grp.height,
                                          1)
        threadsPerThreadgroup:grp];
    [enc endEncoding];
  }
  {
    id<MTLBlitCommandEncoder> blit = [cmd blitCommandEncoder];
    [blit copyFromBuffer:linear
             sourceOffset:0
        sourceBytesPerRow:img.host_pitch
      sourceBytesPerImage:linear_size
               sourceSize:MTLSizeMake(img.width, img.height, 1)
                toTexture:tex
         destinationSlice:0
         destinationLevel:0
        destinationOrigin:MTLOriginMake(0, 0, 0)];
    [blit endEncoding];
  }
  {
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:ReadKernel(h.device)];
    [enc setTexture:tex atIndex:0];
    [enc setBuffer:out offset:0 atIndex:0];
    [enc setBytes:dims length:sizeof(dims) atIndex:1];
    [enc dispatchThreadgroups:MTLSizeMake((img.width + 7) / 8,
                                          (img.height + 7) / 8, 1)
        threadsPerThreadgroup:MTLSizeMake(8, 8, 1)];
    [enc endEncoding];
  }
  [cmd commit];
  [cmd waitUntilCompleted];
  if (cmd.status != MTLCommandBufferStatusCompleted) return {};
  return std::vector<uint8_t>(static_cast<uint8_t*>(out.contents),
                              static_cast<uint8_t*>(out.contents) + texel_bytes);
}

// CPU oracle texels: the expected linear image packed tightly (w*4 per row).
std::vector<uint8_t> OracleTexels(const GuestImage& img) {
  std::vector<uint8_t> t(size_t(img.width) * img.height * 4);
  for (uint32_t y = 0; y < img.height; ++y) {
    std::memcpy(&t[size_t(y) * img.width * 4],
                &img.expected[size_t(y) * img.host_pitch], img.width * 4u);
  }
  return t;
}

// Produce a sampleable RGBA8Unorm texture via the DIRECT path (returns the
// texture; the producing dispatch is complete on return).
id<MTLTexture> ProduceDirectTexture(const GuestImage& img,
                                    xenos::Endian endian) {
  auto& h = H();
  id<MTLBuffer> source =
      [h.device newBufferWithBytes:img.tiled.data() length:img.tiled.size()
                           options:MTLResourceStorageModeShared];
  id<MTLTexture> tex = MakeTexture(h.device, img.width, img.height, true);
  LoadConstants c = MakeConstants(img, endian, 0);
  id<MTLCommandBuffer> cmd = [h.queue commandBuffer];
  id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
  [enc setComputePipelineState:h.direct];
  [enc setBytes:&c length:sizeof(c) atIndex:0];
  [enc setTexture:tex atIndex:1];
  [enc setBuffer:source offset:0 atIndex:2];
  MTLSize grp = MTLSizeMake(MetalLoadShaderPipelines::kThreadgroupSizeX,
                            MetalLoadShaderPipelines::kThreadgroupSizeY, 1);
  uint32_t tx = (img.width + 7u) / 8u;
  [enc dispatchThreadgroups:MTLSizeMake((tx + grp.width - 1) / grp.width,
                                        (img.height + grp.height - 1) /
                                            grp.height, 1)
      threadsPerThreadgroup:grp];
  [enc endEncoding];
  [cmd commit];
  [cmd waitUntilCompleted];
  return cmd.status == MTLCommandBufferStatusCompleted ? tex : nil;
}

// Produce the same texture via the EXISTING buffer+blit path.
id<MTLTexture> ProduceBufferBlitTexture(const GuestImage& img,
                                        xenos::Endian endian) {
  auto& h = H();
  id<MTLBuffer> source =
      [h.device newBufferWithBytes:img.tiled.data() length:img.tiled.size()
                           options:MTLResourceStorageModeShared];
  uint32_t linear_size = img.host_pitch * img.height;
  id<MTLBuffer> linear = [h.device newBufferWithLength:linear_size
                                              options:MTLResourceStorageModePrivate];
  id<MTLTexture> tex = MakeTexture(h.device, img.width, img.height, false);
  LoadConstants c = MakeConstants(img, endian, 0);
  id<MTLCommandBuffer> cmd = [h.queue commandBuffer];
  id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
  [enc setComputePipelineState:(__bridge id<MTLComputePipelineState>)
                                   h.pipelines.pipeline(size_t(h.buffer_index))];
  [enc setBytes:&c length:sizeof(c) atIndex:0];
  [enc setBuffer:linear offset:0 atIndex:1];
  [enc setBuffer:source offset:0 atIndex:2];
  MTLSize grp = MTLSizeMake(MetalLoadShaderPipelines::kThreadgroupSizeX,
                            MetalLoadShaderPipelines::kThreadgroupSizeY, 1);
  uint32_t tx = (img.width + 7u) / 8u;
  [enc dispatchThreadgroups:MTLSizeMake((tx + grp.width - 1) / grp.width,
                                        (img.height + grp.height - 1) /
                                            grp.height, 1)
      threadsPerThreadgroup:grp];
  [enc endEncoding];
  id<MTLBlitCommandEncoder> blit = [cmd blitCommandEncoder];
  [blit copyFromBuffer:linear sourceOffset:0 sourceBytesPerRow:img.host_pitch
    sourceBytesPerImage:linear_size
             sourceSize:MTLSizeMake(img.width, img.height, 1)
              toTexture:tex destinationSlice:0 destinationLevel:0
      destinationOrigin:MTLOriginMake(0, 0, 0)];
  [blit endEncoding];
  [cmd commit];
  [cmd waitUntilCompleted];
  return cmd.status == MTLCommandBufferStatusCompleted ? tex : nil;
}

// Linear-sample `tex` at the given normalized coordinates.
std::vector<simd_float4> SampleAt(id<MTLTexture> tex,
                                  const std::vector<simd_float2>& coords) {
  auto& h = H();
  uint32_t n = uint32_t(coords.size());
  id<MTLBuffer> cbuf = [h.device newBufferWithBytes:coords.data()
                                             length:n * sizeof(simd_float2)
                                            options:MTLResourceStorageModeShared];
  id<MTLBuffer> out = [h.device newBufferWithLength:n * sizeof(simd_float4)
                                           options:MTLResourceStorageModeShared];
  id<MTLCommandBuffer> cmd = [h.queue commandBuffer];
  id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
  [enc setComputePipelineState:SampleKernel(h.device)];
  [enc setTexture:tex atIndex:0];
  [enc setBuffer:cbuf offset:0 atIndex:0];
  [enc setBuffer:out offset:0 atIndex:1];
  [enc setBytes:&n length:sizeof(n) atIndex:2];
  [enc dispatchThreadgroups:MTLSizeMake((n + 63) / 64, 1, 1)
      threadsPerThreadgroup:MTLSizeMake(64, 1, 1)];
  [enc endEncoding];
  [cmd commit];
  [cmd waitUntilCompleted];
  if (cmd.status != MTLCommandBufferStatusCompleted) return {};
  const simd_float4* p = static_cast<const simd_float4*>(out.contents);
  return std::vector<simd_float4>(p, p + n);
}

TEST_CASE("direct texture load: variant pipeline builds on device",
          "[l1][metal][directtex]") {
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  REQUIRE(H().direct != nil);
  REQUIRE(H().buffer_index >= 0);
}

TEST_CASE("direct texture load: byte-identical to CPU oracle AND buffer+blit",
          "[l1][metal][directtex]") {
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  struct Shape {
    uint32_t w, h;
    xenos::Endian e;
  };
  const Shape shapes[] = {
      {320, 180, xenos::Endian::k8in32},
      {1280, 720, xenos::Endian::k8in32},
      {47, 33, xenos::Endian::k8in32},
      {320, 180, xenos::Endian::k8in16},
      {1280, 720, xenos::Endian::k8in16},
  };
  for (const Shape& s : shapes) {
    INFO("shape " << s.w << "x" << s.h << " endian " << uint32_t(s.e));
    GuestImage img = MakeGuestImage(s.w, s.h, s.e);
    std::vector<uint8_t> oracle = OracleTexels(img);
    std::vector<uint8_t> direct = RunDirect(img, s.e);
    std::vector<uint8_t> bufblit = RunBufferBlit(img, s.e);
    REQUIRE(direct.size() == oracle.size());
    REQUIRE(bufblit.size() == oracle.size());
    REQUIRE(bufblit == oracle);   // sanity: the existing shape matches oracle.
    REQUIRE(direct == oracle);    // G0b: direct matches the CPU oracle.
    REQUIRE(direct == bufblit);   // G0b: direct matches buffer+blit exactly.
    // Repeat determinism.
    REQUIRE(RunDirect(img, s.e) == direct);
  }
}

TEST_CASE("direct texture load: 47x33 source covers every padded read group",
          "[l1][metal][directtex]") {
  // The shader reads 8-texel groups over the PADDED width; assert the source
  // allocation MakeGuestImage produces covers the exact read set (pinned so a
  // future change to the sizing can't silently under-allocate on odd widths).
  GuestImage img = MakeGuestImage(47, 33, xenos::Endian::k8in32);
  // 47 rounds to a 32-aligned pitch of 64 and a padded (8-group) width of 48.
  REQUIRE(img.pitch_aligned == 64u);
  REQUIRE(((47u + 7u) & ~7u) == 48u);
  // Independently enumerate EVERY 16-byte uint4 group the direct shader reads
  // — group starts gx in {0,4,...,44} (padded width 48), all rows — and
  // require each read [Tiled2D(gx,y), +16) to fit inside the ACTUAL source
  // allocation `img.tiled.size()`. This is NOT `img.tiled.size() >=
  // DirectShaderReadEnd(...)` (which would be tautological); it fails if
  // DirectShaderReadEnd is ever made too small, because MakeGuestImage would
  // then under-allocate and one of these group reads would run past the end.
  uint32_t group_read_end = 0;
  for (uint32_t y = 0; y < 33; ++y) {
    for (uint32_t gx = 0; gx < 48; gx += 4) {
      uint32_t end = uint32_t(texture_address::Tiled2D(
                         int32_t(gx), int32_t(y), int32_t(img.pitch_aligned),
                         2)) +
                     16u;
      if (end > img.tiled.size()) {
        FAIL("group read (gx=" << gx << ", y=" << y << ") ends at " << end
                               << " > source size " << img.tiled.size());
      }
      group_read_end = std::max(group_read_end, end);
    }
  }
  // Pin the exact end so a layout/pitch regression is caught (this literal is
  // the byte just past the highest group read for 47x33 @ pitch 64).
  REQUIRE(group_read_end == 12400u);
  // The single allocation must also cover the CPU oracle's per-texel 4-byte
  // reads at Tiled2D(x, y), x in [0,width) — kept as an independent check.
  uint32_t oracle_end = 0;
  for (uint32_t y = 0; y < 33; ++y) {
    for (uint32_t x = 0; x < 47; ++x) {
      oracle_end = std::max(
          oracle_end,
          uint32_t(texture_address::Tiled2D(int32_t(x), int32_t(y),
                                            int32_t(img.pitch_aligned), 2)) +
              4u);
    }
  }
  REQUIRE(img.tiled.size() >= oracle_end);
}

TEST_CASE("direct texture load: filtered (linear-sampler) parity with "
          "buffer+blit",
          "[l1][metal][directtex]") {
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  struct Shape {
    uint32_t w, h;
    xenos::Endian e;
  };
  const Shape shapes[] = {
      {320, 180, xenos::Endian::k8in32},
      {1280, 720, xenos::Endian::k8in32},
      {47, 33, xenos::Endian::k8in16},
  };
  for (const Shape& s : shapes) {
    INFO("shape " << s.w << "x" << s.h << " endian " << uint32_t(s.e));
    GuestImage img = MakeGuestImage(s.w, s.h, s.e);
    id<MTLTexture> dtex = ProduceDirectTexture(img, s.e);
    id<MTLTexture> btex = ProduceBufferBlitTexture(img, s.e);
    REQUIRE(dtex != nil);
    REQUIRE(btex != nil);
    // Representative interior coordinates (between texel centers, forcing real
    // bilinear blends) plus every edge/corner (clamp-to-edge behavior).
    std::vector<simd_float2> coords;
    for (uint32_t gy = 0; gy <= 6; ++gy) {
      for (uint32_t gx = 0; gx <= 6; ++gx) {
        // Off-center by a quarter texel so the sampler blends four texels.
        float u = (float(gx) / 6.0f) + (0.25f / float(s.w));
        float v = (float(gy) / 6.0f) + (0.25f / float(s.h));
        coords.push_back(simd_make_float2(u, v));
      }
    }
    // Explicit edges and corners.
    for (float e : {0.0f, 1.0f}) {
      coords.push_back(simd_make_float2(e, 0.5f));
      coords.push_back(simd_make_float2(0.5f, e));
      for (float e2 : {0.0f, 1.0f}) coords.push_back(simd_make_float2(e, e2));
    }
    std::vector<simd_float4> ds = SampleAt(dtex, coords);
    std::vector<simd_float4> bs = SampleAt(btex, coords);
    REQUIRE(ds.size() == coords.size());
    REQUIRE(bs.size() == coords.size());
    // Both textures hold byte-identical RGBA8Unorm content and are sampled by
    // the identical linear sampler/pipeline at identical coordinates, so the
    // filtered results must be EXACTLY equal (bit-for-bit) — not merely within
    // a quantization bound.
    for (size_t i = 0; i < coords.size(); ++i) {
      for (int c = 0; c < 4; ++c) {
        if (ds[i][c] != bs[i][c]) {
          FAIL("coord " << i << " channel " << c << " direct " << ds[i][c]
                        << " != buffer+blit " << bs[i][c]);
        }
      }
    }
  }
}

// ---------------------------------------------------------------------------
// 6.1-G0 (task/metal-texture-load-mip-tail-g0): direct-to-tiled mip chains and
// packed mip tails. Each host mip level is loaded DIRECTLY into a level-scoped
// Metal texture view (mip N of the base aliased as the view's level 0) with
// no linear staging buffer and no staging->texture blit — the mip analog of
// the C1T single-level direct load. Non-packed levels use the existing shader
// verbatim (read position == write position); packed-tail sub-mips pass their
// non-additive sub-tile (px,py) block offset (texture_util::GetPackedMipOffset)
// through the direct variant's otherwise-unused host_offset push constant, so
// the source READ decouples from the destination WRITE without any change to
// the shared load-shader push-constant ABI. The per-level (offset,pitch,size,
// sub-tile) selection is taken from the production layout helpers
// (GetGuestTextureLayout + GetPackedMipOffset), mirroring
// D3D12TextureCache::LoadTextureDataFromResidentMemoryImpl, so no tiled or
// packing math is re-implemented here.
// ---------------------------------------------------------------------------

constexpr uint32_t kMipBpb = 4;  // k_8_8_8_8 bytes per block.

// Per-host-level direct dispatch plan.
struct MipPlan {
  uint32_t host_level;
  uint32_t guest_offset;   // byte base into the shared source buffer
  uint32_t pitch_blocks;   // guest_pitch_aligned (== texels for 32bpp)
  uint32_t width, height;  // this host level's texel dimensions
  uint32_t px, py;         // packed sub-tile block offset (0 if not packed)
};

struct MipImage {
  std::vector<uint8_t> guest;  // base region followed by the mip region
  std::vector<MipPlan> levels;
  uint32_t width, height, level_count;
};

// Exclusive byte end of the guest range the direct shader reads for a level:
// 8-texel groups over the padded width, two uint4 loads per thread, offset by
// the packed sub-tile origin (the exact read set, so the source allocation is
// sized to it rather than over-allocated).
uint32_t LevelReadEnd(const MipPlan& p) {
  uint32_t padded_w = (p.width + 7u) & ~7u;
  uint32_t end = 0;
  for (uint32_t y = 0; y < p.height; ++y) {
    for (uint32_t gx = 0; gx < padded_w; gx += 4u) {
      uint32_t a = p.guest_offset +
                   uint32_t(texture_address::Tiled2D(
                       int32_t(p.px + gx), int32_t(p.py + y),
                       int32_t(p.pitch_blocks), 2)) +
                   16u;
      end = std::max(end, a);
    }
  }
  return end;
}

MipImage MakeMipImage(uint32_t w, uint32_t h, uint32_t mip_max_level) {
  MipImage img;
  img.width = w;
  img.height = h;
  img.level_count = mip_max_level + 1;
  uint32_t pitch_div32 = ((w + 31u) & ~31u) >> 5;
  texture_util::TextureGuestLayout layout = texture_util::GetGuestTextureLayout(
      xenos::DataDimension::k2DOrStacked, pitch_div32, w, h, 1, /*tiled=*/true,
      xenos::TextureFormat::k_8_8_8_8, /*has_packed_levels=*/true,
      /*has_base=*/true, mip_max_level);
  uint32_t packed = layout.packed_level;

  // Base region at offset 0; the mip region follows it, subresource-aligned
  // (base and mips live at separate guest pages in real memory — emulated here
  // as distinct offsets in one buffer, behaviorally identical for the tiled
  // address + byte compare).
  MipPlan base{};
  base.host_level = 0;
  base.guest_offset = 0;
  base.pitch_blocks = layout.base.row_pitch_bytes / kMipBpb;
  base.width = w;
  base.height = h;
  img.levels.push_back(base);
  uint32_t mip_region = xe::align(LevelReadEnd(base),
                                  xenos::kTextureSubresourceAlignmentBytes);

  for (uint32_t level = 1; level <= mip_max_level; ++level) {
    uint32_t store = std::min(level, packed);
    MipPlan p{};
    p.host_level = level;
    p.pitch_blocks = layout.mips[store].row_pitch_bytes / kMipBpb;
    p.width = std::max(w >> level, 1u);
    p.height = std::max(h >> level, 1u);
    p.guest_offset = mip_region + layout.mip_offsets_bytes[store];
    if (packed != UINT32_MAX && level >= packed) {
      uint32_t px, py, pz;
      texture_util::GetPackedMipOffset(w, h, 1,
                                       xenos::TextureFormat::k_8_8_8_8, level,
                                       px, py, pz);
      p.px = px;
      p.py = py;
    }
    img.levels.push_back(p);
  }

  uint32_t total = 0;
  for (const MipPlan& p : img.levels) {
    total = std::max(total, LevelReadEnd(p));
  }
  img.guest.resize(total);
  for (size_t i = 0; i < img.guest.size(); ++i) {
    img.guest[i] = uint8_t(i * 7 + (i >> 6) * 13 + 1);
  }
  return img;
}

// CPU oracle for one host level: the exact bytes the direct shader must
// produce — Tiled2D(px + x, py + y) + guest_offset, GpuSwapped, packed tight.
std::vector<uint8_t> OracleLevel(const MipImage& img, const MipPlan& p,
                                 xenos::Endian endian) {
  std::vector<uint8_t> exp(size_t(p.width) * p.height * 4u);
  for (uint32_t y = 0; y < p.height; ++y) {
    for (uint32_t x = 0; x < p.width; ++x) {
      int32_t off =
          texture_address::Tiled2D(int32_t(p.px + x), int32_t(p.py + y),
                                   int32_t(p.pitch_blocks), 2);
      uint32_t word;
      std::memcpy(&word, &img.guest[p.guest_offset + uint32_t(off)], 4);
      word = xenos::GpuSwap(word, endian);
      std::memcpy(&exp[(size_t(y) * p.width + x) * 4u], &word, 4);
    }
  }
  return exp;
}

// Direct-load an entire mip chain into ONE mipmapped texture via level-scoped
// views, then read every level back — all on ONE command buffer, no CPU wait,
// no linear staging buffer, no blit encoder. Returns per-level tightly-packed
// RGBA8 texels (empty on GPU failure).
std::vector<std::vector<uint8_t>> RunDirectMipChain(const MipImage& img,
                                                    xenos::Endian endian) {
  auto& h = H();
  id<MTLBuffer> source =
      [h.device newBufferWithBytes:img.guest.data()
                            length:img.guest.size()
                           options:MTLResourceStorageModeShared];
  MTLTextureDescriptor* d = [MTLTextureDescriptor
      texture2DDescriptorWithPixelFormat:MTLPixelFormatRGBA8Unorm
                                   width:img.width
                                  height:img.height
                               mipmapped:YES];
  d.mipmapLevelCount = img.level_count;
  d.storageMode = MTLStorageModePrivate;
  d.usage = MTLTextureUsageShaderRead | MTLTextureUsageShaderWrite |
            MTLTextureUsagePixelFormatView;
  id<MTLTexture> tex = [h.device newTextureWithDescriptor:d];
  if (!tex) {
    return {};
  }

  std::vector<id<MTLBuffer>> outs(img.level_count);
  for (const MipPlan& p : img.levels) {
    outs[p.host_level] =
        [h.device newBufferWithLength:size_t(p.width) * p.height * 4u
                             options:MTLResourceStorageModeShared];
  }

  id<MTLCommandBuffer> cmd = [h.queue commandBuffer];
  // (1) Direct-load every level via a level-scoped write view — all on the one
  // command buffer with no commit/wait between them (the real mip-chain load
  // pattern; zero staging bytes, zero blit encoders).
  for (const MipPlan& p : img.levels) {
    id<MTLTexture> level_view =
        [tex newTextureViewWithPixelFormat:MTLPixelFormatRGBA8Unorm
                               textureType:MTLTextureType2D
                                    levels:NSMakeRange(p.host_level, 1)
                                    slices:NSMakeRange(0, 1)];
    LoadConstants c = {};
    c.is_tiled_3d_endian_scale = 1u | (uint32_t(endian) << 2);
    c.guest_offset = p.guest_offset;
    c.guest_pitch_aligned = p.pitch_blocks;
    c.size_blocks[0] = p.width;
    c.size_blocks[1] = p.height;
    c.size_blocks[2] = 1;
    // Packed sub-tile source offset (px low 16 bits, py high 16); 0 for base
    // and non-packed levels -> read position == write position.
    c.host_offset = (p.px & 0xFFFFu) | (p.py << 16u);
    c.host_pitch = ((p.width * 4u) + 255u) & ~255u;
    c.height_texels = p.height;
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:h.direct];
    [enc setBytes:&c length:sizeof(c) atIndex:0];
    [enc setTexture:level_view atIndex:1];
    [enc setBuffer:source offset:0 atIndex:2];
    MTLSize grp = MTLSizeMake(MetalLoadShaderPipelines::kThreadgroupSizeX,
                              MetalLoadShaderPipelines::kThreadgroupSizeY, 1);
    uint32_t tx = (p.width + 7u) / 8u;
    [enc dispatchThreadgroups:MTLSizeMake((tx + grp.width - 1) / grp.width,
                                          (p.height + grp.height - 1) /
                                              grp.height,
                                          1)
        threadsPerThreadgroup:grp];
    [enc endEncoding];
  }
  // (2) Read every level back through a level-scoped read view.
  for (const MipPlan& p : img.levels) {
    id<MTLTexture> level_view =
        [tex newTextureViewWithPixelFormat:MTLPixelFormatRGBA8Unorm
                               textureType:MTLTextureType2D
                                    levels:NSMakeRange(p.host_level, 1)
                                    slices:NSMakeRange(0, 1)];
    uint32_t dims[2] = {p.width, p.height};
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:ReadKernel(h.device)];
    [enc setTexture:level_view atIndex:0];
    [enc setBuffer:outs[p.host_level] offset:0 atIndex:0];
    [enc setBytes:dims length:sizeof(dims) atIndex:1];
    [enc dispatchThreadgroups:MTLSizeMake((p.width + 7) / 8, (p.height + 7) / 8,
                                          1)
        threadsPerThreadgroup:MTLSizeMake(8, 8, 1)];
    [enc endEncoding];
  }
  [cmd commit];
  [cmd waitUntilCompleted];
  if (cmd.status != MTLCommandBufferStatusCompleted) {
    return {};
  }
  std::vector<std::vector<uint8_t>> result(img.level_count);
  for (const MipPlan& p : img.levels) {
    uint32_t n = p.width * p.height * 4u;
    result[p.host_level].assign(
        static_cast<uint8_t*>(outs[p.host_level].contents),
        static_cast<uint8_t*>(outs[p.host_level].contents) + n);
  }
  return result;
}

TEST_CASE("direct texture load: mip chain + packed tail byte-identical to oracle",
          "[l1][metal][directtex]") {
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  struct Shape {
    uint32_t w, h, max_level;
    xenos::Endian e;
    const char* name;
  };
  const Shape shapes[] = {
      {256, 256, 8, xenos::Endian::k8in32, "256x256 pow2 k8in32"},
      {256, 256, 8, xenos::Endian::k8in16, "256x256 pow2 k8in16"},
      {96, 48, 6, xenos::Endian::k8in32, "96x48 npot k8in32"},
      {160, 96, 7, xenos::Endian::k8in16, "160x96 npot k8in16"},
  };
  for (const Shape& s : shapes) {
    INFO(s.name);
    MipImage img = MakeMipImage(s.w, s.h, s.max_level);
    std::vector<std::vector<uint8_t>> got = RunDirectMipChain(img, s.e);
    REQUIRE(got.size() == size_t(img.level_count));
    for (const MipPlan& p : img.levels) {
      INFO("level " << p.host_level << " " << p.width << "x" << p.height
                    << " px " << p.px << " py " << p.py);
      std::vector<uint8_t> oracle = OracleLevel(img, p, s.e);
      REQUIRE(got[p.host_level].size() == oracle.size());
      REQUIRE(got[p.host_level] == oracle);
    }
    // Repeat determinism: the identical chain re-loaded is bit-identical.
    std::vector<std::vector<uint8_t>> got2 = RunDirectMipChain(img, s.e);
    for (const MipPlan& p : img.levels) {
      REQUIRE(got2[p.host_level] == got[p.host_level]);
    }
  }
}

TEST_CASE("direct texture load: packed tail places sub-mips at nonzero offsets",
          "[l1][metal][directtex]") {
  // Device-free structural proof that the mip-chain byte case above genuinely
  // exercises the decoupled source-read path: the 256x256 chain has a packed
  // tail spanning multiple levels, at least one at a nonzero (px,py) sub-tile
  // origin (so host_offset != 0 is actually driven, not just the offset-0
  // base/non-packed path). Uses the production GetPackedMipOffset helper.
  MipImage img = MakeMipImage(256, 256, 8);
  uint32_t packed_levels = 0;
  uint32_t nonzero_offsets = 0;
  for (const MipPlan& p : img.levels) {
    uint32_t px, py, pz;
    if (texture_util::GetPackedMipOffset(256, 256, 1,
                                         xenos::TextureFormat::k_8_8_8_8,
                                         p.host_level, px, py, pz)) {
      ++packed_levels;
      // The plan must carry exactly what the helper reports.
      REQUIRE(p.px == px);
      REQUIRE(p.py == py);
    }
    if (p.px != 0 || p.py != 0) {
      ++nonzero_offsets;
    }
  }
  REQUIRE(packed_levels >= 2);
  REQUIRE(nonzero_offsets >= 1);
}

