using metal::MetalLoadShaderPipelines;
using LoadConstants = MetalLoadShaderPipelines::LoadConstants;
constexpr uint32_t kRowAlign = 256;

struct DirectHarness {
  id<MTLDevice> device = nil;
  id<MTLCommandQueue> queue = nil;
  MetalLoadShaderPipelines pipelines;  // buffer 32bpb (existing family).
  id<MTLComputePipelineState> direct = nil;  // the C1T direct variant.
  int buffer_index = -1;
  bool ok = false;

  DirectHarness() {
    device = MTLCreateSystemDefaultDevice();
    if (!device) {
      return;
    }
    queue = [device newCommandQueue];
    if (!queue || !pipelines.Initialize((__bridge void*)device)) {
      return;
    }
    buffer_index = pipelines.FindIndex("texture_load_32bpb_cs");
    // Build the direct-variant pipeline from the generated metallib.
    dispatch_data_t data = dispatch_data_create(
        texture_load_32bpb_direct_cs_metallib,
        sizeof(texture_load_32bpb_direct_cs_metallib),
        dispatch_get_main_queue(), DISPATCH_DATA_DESTRUCTOR_DEFAULT);
    NSError* err = nil;
    id<MTLLibrary> lib = [device newLibraryWithData:data error:&err];
    if (lib) {
      id<MTLFunction> fn = [lib newFunctionWithName:@"entry_xe"];
      if (fn) {
        direct = [device newComputePipelineStateWithFunction:fn error:&err];
      }
    }
    ok = pipelines.initialized() && buffer_index >= 0 && direct != nil;
  }
};

DirectHarness& H() {
  static DirectHarness h;
  return h;
}

#define REQUIRE_DEVICE()                                        \
  do {                                                          \
    if (!H().device) {                                          \
      FAIL("No Metal device: these cases must run on the M4."); \
    }                                                           \
  } while (0)

struct GuestImage {
  std::vector<uint8_t> tiled;     // guest-layout source bytes.
  std::vector<uint8_t> expected;  // CPU-oracle linear rows at host_pitch.
  uint32_t width, height, pitch_aligned, host_pitch;
};

GuestImage MakeGuestImage(uint32_t width, uint32_t height,
                          xenos::Endian endian) {
  GuestImage img;
  img.width = width;
  img.height = height;
  img.pitch_aligned = (width + 31u) & ~31u;
  img.host_pitch = ((width * 4u) + (kRowAlign - 1)) & ~(kRowAlign - 1);
  int32_t max_off = 0;
  for (uint32_t y = 0; y < height; ++y) {
    for (uint32_t x = 0; x < width; ++x) {
      max_off = std::max(max_off, texture_address::Tiled2D(int32_t(x),
                                                           int32_t(y),
                                                           img.pitch_aligned,
                                                           2));
    }
  }
  img.tiled.resize(uint32_t(max_off) + 16);
  for (size_t i = 0; i < img.tiled.size(); ++i) {
    img.tiled[i] = uint8_t(i * 5 + (i >> 7) * 11 + 3);
  }
  img.expected.assign(size_t(img.host_pitch) * height, 0);
  for (uint32_t y = 0; y < height; ++y) {
    for (uint32_t x = 0; x < width; ++x) {
      int32_t off = texture_address::Tiled2D(int32_t(x), int32_t(y),
                                             img.pitch_aligned, 2);
      uint32_t word;
      std::memcpy(&word, &img.tiled[off], 4);
      word = xenos::GpuSwap(word, endian);
      std::memcpy(&img.expected[size_t(y) * img.host_pitch + x * 4u], &word, 4);
    }
  }
  return img;
}

LoadConstants MakeConstants(const GuestImage& img, xenos::Endian endian,
                            uint32_t host_offset) {
  LoadConstants c = {};
  c.is_tiled_3d_endian_scale = 1u | (uint32_t(endian) << 2);
  c.guest_offset = 0;
  c.guest_pitch_aligned = img.pitch_aligned;
  c.size_blocks[0] = img.width;
  c.size_blocks[1] = img.height;
  c.size_blocks[2] = 1;
  c.host_offset = host_offset;
  c.host_pitch = img.host_pitch;
  c.height_texels = img.height;
  return c;
}

// Reads an RGBA8Unorm texture's texels back into a tightly-packed w*h*4 buffer
// via a compute read kernel (cross-encoder, same command buffer, no CPU wait
// between the producing dispatch and this read).
id<MTLComputePipelineState> ReadKernel(id<MTLDevice> device) {
  static id<MTLComputePipelineState> ps = nil;
  if (ps) return ps;
  NSString* src = @R"MSL(
    #include <metal_stdlib>
    using namespace metal;
    kernel void read_texels(texture2d<float, access::read> tex [[texture(0)]],
                            device uchar4* out [[buffer(0)]],
                            constant uint2& dims [[buffer(1)]],
                            uint2 gid [[thread_position_in_grid]]) {
      if (gid.x >= dims.x || gid.y >= dims.y) return;
      out[gid.y * dims.x + gid.x] = uchar4(round(tex.read(gid) * 255.0f));
    })MSL";
  NSError* e = nil;
  id<MTLLibrary> lib = [device newLibraryWithSource:src options:nil error:&e];
  id<MTLFunction> fn = [lib newFunctionWithName:@"read_texels"];
  ps = [device newComputePipelineStateWithFunction:fn error:&e];
  return ps;
}

id<MTLTexture> MakeTexture(id<MTLDevice> device, uint32_t w, uint32_t h,
                           bool writable) {
  MTLTextureDescriptor* d = [MTLTextureDescriptor
      texture2DDescriptorWithPixelFormat:MTLPixelFormatRGBA8Unorm
                                   width:w
                                  height:h
                               mipmapped:NO];
  d.storageMode = MTLStorageModePrivate;
  d.usage = writable ? (MTLTextureUsageShaderRead | MTLTextureUsageShaderWrite)
                     : MTLTextureUsageShaderRead;
  return [device newTextureWithDescriptor:d];
}

// DIRECT path: dispatch the variant to write `tex` directly, then read it
// back — one command buffer, no CPU wait.
std::vector<uint8_t> RunDirect(const GuestImage& img, xenos::Endian endian) {
  auto& h = H();
  id<MTLBuffer> source =
      [h.device newBufferWithBytes:img.tiled.data()
                            length:img.tiled.size()
                           options:MTLResourceStorageModeShared];
  id<MTLTexture> tex = MakeTexture(h.device, img.width, img.height, true);
  uint32_t texel_bytes = img.width * img.height * 4u;
  id<MTLBuffer> out = [h.device newBufferWithLength:texel_bytes
                                            options:MTLResourceStorageModeShared];
  uint32_t dims[2] = {img.width, img.height};
  LoadConstants c = MakeConstants(img, endian, 0);
  id<MTLCommandBuffer> cmd = [h.queue commandBuffer];
  {
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:h.direct];
    [enc setBytes:&c length:sizeof(c) atIndex:0];
    [enc setTexture:tex atIndex:1];
    [enc setBuffer:source offset:0 atIndex:2];
    MTLSize grp = MTLSizeMake(MetalLoadShaderPipelines::kThreadgroupSizeX,
                              MetalLoadShaderPipelines::kThreadgroupSizeY, 1);
    uint32_t tx = (img.width + 7u) / 8u;
    [enc dispatchThreadgroups:MTLSizeMake((tx + grp.width - 1) / grp.width,
                                          (img.height + grp.height - 1) /
                                              grp.height,
                                          1)
        threadsPerThreadgroup:grp];
    [enc endEncoding];
  }
  {
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:ReadKernel(h.device)];
    [enc setTexture:tex atIndex:0];
    [enc setBuffer:out offset:0 atIndex:0];
    [enc setBytes:dims length:sizeof(dims) atIndex:1];
    [enc dispatchThreadgroups:MTLSizeMake((img.width + 7) / 8,
                                          (img.height + 7) / 8, 1)
        threadsPerThreadgroup:MTLSizeMake(8, 8, 1)];
    [enc endEncoding];
  }
  [cmd commit];
  [cmd waitUntilCompleted];
  if (cmd.status != MTLCommandBufferStatusCompleted) return {};
  return std::vector<uint8_t>(static_cast<uint8_t*>(out.contents),
                              static_cast<uint8_t*>(out.contents) + texel_bytes);
}

// BUFFER+BLIT path (the existing shape): load 32bpb into a linear buffer,
// blit to the texture, read back.
std::vector<uint8_t> RunBufferBlit(const GuestImage& img, xenos::Endian endian) {
  auto& h = H();
  id<MTLBuffer> source =
      [h.device newBufferWithBytes:img.tiled.data()
                            length:img.tiled.size()
                           options:MTLResourceStorageModeShared];
  uint32_t linear_size = img.host_pitch * img.height;
  id<MTLBuffer> linear = [h.device newBufferWithLength:linear_size
                                              options:MTLResourceStorageModePrivate];
  id<MTLTexture> tex = MakeTexture(h.device, img.width, img.height, false);
  uint32_t texel_bytes = img.width * img.height * 4u;
  id<MTLBuffer> out = [h.device newBufferWithLength:texel_bytes
                                            options:MTLResourceStorageModeShared];
  uint32_t dims[2] = {img.width, img.height};
  LoadConstants c = MakeConstants(img, endian, 0);
  id<MTLCommandBuffer> cmd = [h.queue commandBuffer];
  {
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:(__bridge id<MTLComputePipelineState>)
                                     h.pipelines.pipeline(size_t(h.buffer_index))];
    [enc setBytes:&c length:sizeof(c) atIndex:0];
    [enc setBuffer:linear offset:0 atIndex:1];
    [enc setBuffer:source offset:0 atIndex:2];
    MTLSize grp = MTLSizeMake(MetalLoadShaderPipelines::kThreadgroupSizeX,
                              MetalLoadShaderPipelines::kThreadgroupSizeY, 1);
    uint32_t tx = (img.width + 7u) / 8u;
    [enc dispatchThreadgroups:MTLSizeMake((tx + grp.width - 1) / grp.width,
                                          (img.height + grp.height - 1) /
                                              grp.height,
                                          1)
        threadsPerThreadgroup:grp];
    [enc endEncoding];
  }
  {
    id<MTLBlitCommandEncoder> blit = [cmd blitCommandEncoder];
    [blit copyFromBuffer:linear
             sourceOffset:0
        sourceBytesPerRow:img.host_pitch
      sourceBytesPerImage:linear_size
               sourceSize:MTLSizeMake(img.width, img.height, 1)
                toTexture:tex
         destinationSlice:0
         destinationLevel:0
        destinationOrigin:MTLOriginMake(0, 0, 0)];
    [blit endEncoding];
  }
  {
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:ReadKernel(h.device)];
    [enc setTexture:tex atIndex:0];
    [enc setBuffer:out offset:0 atIndex:0];
    [enc setBytes:dims length:sizeof(dims) atIndex:1];
    [enc dispatchThreadgroups:MTLSizeMake((img.width + 7) / 8,
                                          (img.height + 7) / 8, 1)
        threadsPerThreadgroup:MTLSizeMake(8, 8, 1)];
    [enc endEncoding];
  }
  [cmd commit];
  [cmd waitUntilCompleted];
  if (cmd.status != MTLCommandBufferStatusCompleted) return {};
  return std::vector<uint8_t>(static_cast<uint8_t*>(out.contents),
                              static_cast<uint8_t*>(out.contents) + texel_bytes);
}

// CPU oracle texels: the expected linear image packed tightly (w*4 per row).
std::vector<uint8_t> OracleTexels(const GuestImage& img) {
  std::vector<uint8_t> t(size_t(img.width) * img.height * 4);
  for (uint32_t y = 0; y < img.height; ++y) {
    std::memcpy(&t[size_t(y) * img.width * 4],
                &img.expected[size_t(y) * img.host_pitch], img.width * 4u);
  }
  return t;
}

TEST_CASE("direct texture load: variant pipeline builds on device",
          "[l1][metal][directtex]") {
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  REQUIRE(H().direct != nil);
  REQUIRE(H().buffer_index >= 0);
}

TEST_CASE("direct texture load: byte-identical to CPU oracle AND buffer+blit",
          "[l1][metal][directtex]") {
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  struct Shape {
    uint32_t w, h;
    xenos::Endian e;
  };
  const Shape shapes[] = {
      {320, 180, xenos::Endian::k8in32},
      {1280, 720, xenos::Endian::k8in32},
      {47, 33, xenos::Endian::k8in32},
      {320, 180, xenos::Endian::k8in16},
      {1280, 720, xenos::Endian::k8in16},
  };
  for (const Shape& s : shapes) {
    INFO("shape " << s.w << "x" << s.h << " endian " << uint32_t(s.e));
    GuestImage img = MakeGuestImage(s.w, s.h, s.e);
    std::vector<uint8_t> oracle = OracleTexels(img);
    std::vector<uint8_t> direct = RunDirect(img, s.e);
    std::vector<uint8_t> bufblit = RunBufferBlit(img, s.e);
    REQUIRE(direct.size() == oracle.size());
    REQUIRE(bufblit.size() == oracle.size());
    REQUIRE(bufblit == oracle);   // sanity: the existing shape matches oracle.
    REQUIRE(direct == oracle);    // G0b: direct matches the CPU oracle.
    REQUIRE(direct == bufblit);   // G0b: direct matches buffer+blit exactly.
    // Repeat determinism.
    REQUIRE(RunDirect(img, s.e) == direct);
  }
}

