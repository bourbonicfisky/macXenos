// Linear-sample `tex` at the given normalized coordinates.
std::vector<simd_float4> SampleAt(id<MTLTexture> tex,
                                  const std::vector<simd_float2>& coords) {
  auto& h = H();
  uint32_t n = uint32_t(coords.size());
  id<MTLBuffer> cbuf = [h.device newBufferWithBytes:coords.data()
                                             length:n * sizeof(simd_float2)
                                            options:MTLResourceStorageModeShared];
  id<MTLBuffer> out = [h.device newBufferWithLength:n * sizeof(simd_float4)
                                           options:MTLResourceStorageModeShared];
  id<MTLCommandBuffer> cmd = [h.queue commandBuffer];
  id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
  [enc setComputePipelineState:SampleKernel(h.device)];
  [enc setTexture:tex atIndex:0];
  [enc setBuffer:cbuf offset:0 atIndex:0];
  [enc setBuffer:out offset:0 atIndex:1];
  [enc setBytes:&n length:sizeof(n) atIndex:2];
  [enc dispatchThreadgroups:MTLSizeMake((n + 63) / 64, 1, 1)
      threadsPerThreadgroup:MTLSizeMake(64, 1, 1)];
  [enc endEncoding];
  [cmd commit];
  [cmd waitUntilCompleted];
  if (cmd.status != MTLCommandBufferStatusCompleted) return {};
  const simd_float4* p = static_cast<const simd_float4*>(out.contents);
  return std::vector<simd_float4>(p, p + n);
}

TEST_CASE("direct texture load: variant pipeline builds on device",
          "[l1][metal][directtex]") {
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  REQUIRE(H().direct != nil);
  REQUIRE(H().buffer_index >= 0);
}

TEST_CASE("direct texture load: byte-identical to CPU oracle AND buffer+blit",
          "[l1][metal][directtex]") {
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  struct Shape {
    uint32_t w, h;
    xenos::Endian e;
  };
  const Shape shapes[] = {
      {320, 180, xenos::Endian::k8in32},
      {1280, 720, xenos::Endian::k8in32},
      {47, 33, xenos::Endian::k8in32},
      {320, 180, xenos::Endian::k8in16},
      {1280, 720, xenos::Endian::k8in16},
  };
  for (const Shape& s : shapes) {
    INFO("shape " << s.w << "x" << s.h << " endian " << uint32_t(s.e));
    GuestImage img = MakeGuestImage(s.w, s.h, s.e);
    std::vector<uint8_t> oracle = OracleTexels(img);
    std::vector<uint8_t> direct = RunDirect(img, s.e);
    std::vector<uint8_t> bufblit = RunBufferBlit(img, s.e);
    REQUIRE(direct.size() == oracle.size());
    REQUIRE(bufblit.size() == oracle.size());
    REQUIRE(bufblit == oracle);   // sanity: the existing shape matches oracle.
    REQUIRE(direct == oracle);    // G0b: direct matches the CPU oracle.
    REQUIRE(direct == bufblit);   // G0b: direct matches buffer+blit exactly.
    // Repeat determinism.
    REQUIRE(RunDirect(img, s.e) == direct);
  }
}

TEST_CASE("direct texture load: 47x33 source covers every padded read group",
          "[l1][metal][directtex]") {
  // The shader reads 8-texel groups over the PADDED width; assert the source
  // allocation MakeGuestImage produces covers the exact read set (pinned so a
  // future change to the sizing can't silently under-allocate on odd widths).
  GuestImage img = MakeGuestImage(47, 33, xenos::Endian::k8in32);
  // 47 rounds to a 32-aligned pitch of 64 and a padded (8-group) width of 48.
  REQUIRE(img.pitch_aligned == 64u);
  REQUIRE(((47u + 7u) & ~7u) == 48u);
  // Independently enumerate EVERY 16-byte uint4 group the direct shader reads
  // — group starts gx in {0,4,...,44} (padded width 48), all rows — and
  // require each read [Tiled2D(gx,y), +16) to fit inside the ACTUAL source
  // allocation `img.tiled.size()`. This is NOT `img.tiled.size() >=
  // DirectShaderReadEnd(...)` (which would be tautological); it fails if
  // DirectShaderReadEnd is ever made too small, because MakeGuestImage would
  // then under-allocate and one of these group reads would run past the end.
  uint32_t group_read_end = 0;
  for (uint32_t y = 0; y < 33; ++y) {
    for (uint32_t gx = 0; gx < 48; gx += 4) {
      uint32_t end = uint32_t(texture_address::Tiled2D(
                         int32_t(gx), int32_t(y), int32_t(img.pitch_aligned),
                         2)) +
                     16u;
      if (end > img.tiled.size()) {
        FAIL("group read (gx=" << gx << ", y=" << y << ") ends at " << end
                               << " > source size " << img.tiled.size());
      }
      group_read_end = std::max(group_read_end, end);
    }
  }
  // Pin the exact end so a layout/pitch regression is caught (this literal is
  // the byte just past the highest group read for 47x33 @ pitch 64).
  REQUIRE(group_read_end == 12400u);
  // The single allocation must also cover the CPU oracle's per-texel 4-byte
  // reads at Tiled2D(x, y), x in [0,width) — kept as an independent check.
  uint32_t oracle_end = 0;
  for (uint32_t y = 0; y < 33; ++y) {
    for (uint32_t x = 0; x < 47; ++x) {
      oracle_end = std::max(
          oracle_end,
          uint32_t(texture_address::Tiled2D(int32_t(x), int32_t(y),
                                            int32_t(img.pitch_aligned), 2)) +
              4u);
    }
  }
  REQUIRE(img.tiled.size() >= oracle_end);
}

TEST_CASE("direct texture load: filtered (linear-sampler) parity with "
