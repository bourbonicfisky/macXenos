// ---------------------------------------------------------------------------
// 6.2-G0 (task/metal-dxt-direct-load-g0): DXT4_5 direct decode-to-tiled.
// texture_load_dxt5_rgba8_direct decodes guest DXT5 blocks (through the SAME
// shared XeDXT5BlockToRGBA8Rows helper the linear texture_load_dxt5_rgba8 now
// consumes) and writes RGBA8 texels DIRECTLY into an optimally-tiled Metal
// texture (level-scoped views for mips), with no linear staging buffer and no
// blit. The reference is the shared LINEAR shader's RGBA8 output — a
// DECODE-to-RGBA8 representation, explicitly NOT the canonical Metal DXT4_5
// path (hardware-sampled BC3). Because both shaders share the decode helper,
// direct-vs-shared proves the store + packed-offset mechanism; a separate
// flat/endpoint independent oracle (trivial 565->888, no interpolation math)
// gates the shared decode helper's own correctness.
// ---------------------------------------------------------------------------

constexpr uint32_t kDxtBpb = 16;        // DXT5 bytes per 4x4 block.
constexpr uint32_t kDxtBlockLog2 = 4;   // log2(16).
constexpr uint32_t kDxtBlockTexels = 4;

// A 16-byte DXT5 block from logical fields (guest byte order). With endian
// kNone the shader sees these bytes verbatim after XeEndianSwap32.
// Layout: a0,a1, 6 bytes alpha indices (3 bits/texel, texel 0 = bits 0..2),
// c0(lo,hi), c1(lo,hi), 4 bytes color indices (2 bits/texel).
std::array<uint8_t, 16> MakeDxt5Block(uint8_t a0, uint8_t a1, uint64_t alpha_idx,
                                      uint16_t c0, uint16_t c1,
                                      uint32_t color_idx) {
  std::array<uint8_t, 16> b{};
  b[0] = a0;
  b[1] = a1;
  for (int i = 0; i < 6; ++i) b[2 + i] = uint8_t((alpha_idx >> (8 * i)) & 0xFF);
  b[8] = uint8_t(c0 & 0xFF);
  b[9] = uint8_t(c0 >> 8);
  b[10] = uint8_t(c1 & 0xFF);
  b[11] = uint8_t(c1 >> 8);
  for (int i = 0; i < 4; ++i) b[12 + i] = uint8_t((color_idx >> (8 * i)) & 0xFF);
  return b;
}

// Standard 565 -> 888 with low-bit replication (independent of the shader's
// internal 8-in-10 form; exact for flat/endpoint texels where no mixing runs).
uint32_t Expand565Rgba(uint16_t c, uint8_t a) {
  uint32_t r5 = (c >> 11) & 0x1F, g6 = (c >> 5) & 0x3F, b5 = c & 0x1F;
  uint32_t r = (r5 << 3) | (r5 >> 2);
  uint32_t g = (g6 << 2) | (g6 >> 4);
  uint32_t b = (b5 << 3) | (b5 >> 2);
  return r | (g << 8) | (b << 16) | (uint32_t(a) << 24);
}

// Build a tiled DXT5 source buffer (block-major tiled addressing) whose block
// (bx,by) at guest_offset holds block_fn(bx,by). Sized to cover the padded
// read set the 2-block-per-thread shader touches.
template <typename BlockFn>
void WriteTiledDxt5(std::vector<uint8_t>& buf, uint32_t guest_offset,
                    uint32_t blocks_w, uint32_t blocks_h,
                    uint32_t pitch_blocks_aligned, BlockFn block_fn) {
  uint32_t padded_bw = (blocks_w + 1u) & ~1u;  // 2 blocks/thread along X.
  for (uint32_t by = 0; by < blocks_h; ++by) {
    for (uint32_t bx = 0; bx < padded_bw; ++bx) {
      uint32_t off = guest_offset +
                     uint32_t(texture_address::Tiled2D(int32_t(bx), int32_t(by),
                                                       int32_t(pitch_blocks_aligned),
                                                       int32_t(kDxtBlockLog2)));
      if (off + kDxtBpb > buf.size()) {
        buf.resize(off + kDxtBpb, 0);
      }
      std::array<uint8_t, 16> blk =
          (bx < blocks_w) ? block_fn(bx, by) : std::array<uint8_t, 16>{};
      std::memcpy(&buf[off], blk.data(), kDxtBpb);
    }
  }
}

// Dispatch a DXT5 load (shared or direct) — the 2-blocks-per-thread contract:
// thread.x covers ceil(blocks_w/2), thread.y covers blocks_h, threadgroup 4x32.
void DispatchDxt5(id<MTLComputeCommandEncoder> enc, uint32_t blocks_w,
                  uint32_t blocks_h) {
  MTLSize grp = MTLSizeMake(MetalLoadShaderPipelines::kThreadgroupSizeX,
                            MetalLoadShaderPipelines::kThreadgroupSizeY, 1);
  uint32_t tx = (blocks_w + 1u) / 2u;
  [enc dispatchThreadgroups:MTLSizeMake((tx + grp.width - 1) / grp.width,
                                        (blocks_h + grp.height - 1) / grp.height,
                                        1)
      threadsPerThreadgroup:grp];
}

// Linear-reference row pitch in bytes. The 2-blocks-per-thread shader writes
// the padding block for an odd block-width (block N of an N-block-wide image);
// production sizes the decoded staging footprint to a 256-aligned row (the
// D3D12/6.1 buffer+blit shape), which both keeps every
// byte_buffer_align16_store16 row address 16-byte aligned (the MSL store
// reinterprets a uint4) and is wide enough that the padding block never wraps
// into the next row. Match that exactly rather than merely rounding to an even
// block width.
uint32_t SharedLinearPitchBytes(uint32_t blocks_w) {
  return ((blocks_w * 4u * 4u) + 255u) & ~255u;  // align256(ext_w_texels * 4).
}

// Canary guard around host output buffers: a sentinel-filled prefix/suffix that
// must remain untouched after the dispatch (catches an under/over-run the
// exact-sized buffer would hide). 256 bytes keeps the guarded content offset
// 16-byte aligned for the align16 store.
constexpr uint32_t kGuardBytes = 256;
constexpr uint8_t kGuardByte = 0xCD;

void RequireGuardsIntact(id<MTLBuffer> buf, uint32_t content_bytes,
                         const char* what) {
  const uint8_t* p = static_cast<const uint8_t*>(buf.contents);
  for (uint32_t i = 0; i < kGuardBytes; ++i) {
    if (p[i] != kGuardByte) {
      FAIL(what << " prefix guard clobbered at byte " << i);
    }
  }
  const uint8_t* suffix = p + kGuardBytes + content_bytes;
  for (uint32_t i = 0; i < kGuardBytes; ++i) {
    if (suffix[i] != kGuardByte) {
      FAIL(what << " suffix guard clobbered at byte " << i);
    }
  }
}

// Run the shared LINEAR texture_load_dxt5_rgba8 over an extent of blocks_w x
// blocks_h blocks; returns RGBA8 rows at SharedLinearPitchBytes(blocks_w)
// stride, height = blocks_h*4 rows. The linear dest is bound at a guarded
// offset (host_offset = kGuardBytes) with prefix/suffix canaries asserted
// intact.
std::vector<uint8_t> RunSharedDxt5Linear(const std::vector<uint8_t>& src,
                                         uint32_t guest_offset,
                                         uint32_t pitch_blocks_aligned,
                                         uint32_t blocks_w, uint32_t blocks_h,
                                         xenos::Endian endian) {
  auto& h = H();
  uint32_t ext_h = blocks_h * 4u;
  uint32_t host_pitch = SharedLinearPitchBytes(blocks_w);
  uint32_t content = host_pitch * ext_h;
  uint32_t total = kGuardBytes + content + kGuardBytes;
  id<MTLBuffer> source =
      [h.device newBufferWithBytes:src.data()
                            length:src.size()
                           options:MTLResourceStorageModeShared];
  id<MTLBuffer> dest = [h.device newBufferWithLength:total
                                            options:MTLResourceStorageModeShared];
  std::memset(dest.contents, kGuardByte, total);
  LoadConstants c = {};
  c.is_tiled_3d_endian_scale = 1u | (uint32_t(endian) << 2);
  c.guest_offset = guest_offset;
  c.guest_pitch_aligned = pitch_blocks_aligned;
  c.size_blocks[0] = blocks_w;
  c.size_blocks[1] = blocks_h;
  c.size_blocks[2] = 1;
  c.host_offset = kGuardBytes;  // write past the prefix guard.
  c.host_pitch = host_pitch;
  c.height_texels = ext_h;
  id<MTLCommandBuffer> cmd = [h.queue commandBuffer];
  id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
  [enc setComputePipelineState:(__bridge id<MTLComputePipelineState>)
                                   h.pipelines.pipeline(size_t(h.dxt5_index))];
  [enc setBytes:&c length:sizeof(c) atIndex:0];
  [enc setBuffer:dest offset:0 atIndex:1];
  [enc setBuffer:source offset:0 atIndex:2];
  DispatchDxt5(enc, blocks_w, blocks_h);
  [enc endEncoding];
  [cmd commit];
  [cmd waitUntilCompleted];
  if (cmd.status != MTLCommandBufferStatusCompleted) return {};
  RequireGuardsIntact(dest, content, "shared linear dest");
  const uint8_t* base = static_cast<const uint8_t*>(dest.contents) + kGuardBytes;
  return std::vector<uint8_t>(base, base + content);
}

// Run the DIRECT texture_load_dxt5_rgba8_direct into an optionally level-scoped
// view; sub-mip size (subw x subh) texels, packed sub-tile block offset
// (px,py). Returns tightly-packed subw*subh*4 RGBA8. `tex` and `level` let the
// caller drive a mip chain; pass a fresh single-level texture otherwise.
std::vector<uint8_t> RunDirectDxt5(const std::vector<uint8_t>& src,
                                   uint32_t guest_offset,
                                   uint32_t pitch_blocks_aligned, uint32_t subw,
                                   uint32_t subh, uint32_t px, uint32_t py,
                                   xenos::Endian endian, id<MTLTexture> tex,
                                   uint32_t level) {
  auto& h = H();
  id<MTLBuffer> source =
      [h.device newBufferWithBytes:src.data()
                            length:src.size()
                           options:MTLResourceStorageModeShared];
  id<MTLTexture> level_view =
      [tex newTextureViewWithPixelFormat:MTLPixelFormatRGBA8Unorm
                             textureType:MTLTextureType2D
                                  levels:NSMakeRange(level, 1)
                                  slices:NSMakeRange(0, 1)];
  uint32_t blocks_w = (subw + 3u) / 4u, blocks_h = (subh + 3u) / 4u;
  uint32_t texel_bytes = subw * subh * 4u;
  uint32_t out_total = kGuardBytes + texel_bytes + kGuardBytes;
  id<MTLBuffer> out = [h.device newBufferWithLength:out_total
                                           options:MTLResourceStorageModeShared];
  std::memset(out.contents, kGuardByte, out_total);
  uint32_t dims[2] = {subw, subh};
  LoadConstants c = {};
  c.is_tiled_3d_endian_scale = 1u | (uint32_t(endian) << 2);
  c.guest_offset = guest_offset;
  c.guest_pitch_aligned = pitch_blocks_aligned;
  c.size_blocks[0] = blocks_w;
  c.size_blocks[1] = blocks_h;
  c.size_blocks[2] = 1;
  c.host_offset = (px & 0xFFFFu) | (py << 16u);  // packed sub-tile block offset
  c.host_pitch = subw;                            // width texel bound
  c.height_texels = subh;                         // height texel bound
  id<MTLCommandBuffer> cmd = [h.queue commandBuffer];
  {
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:h.dxt5_direct];
    [enc setBytes:&c length:sizeof(c) atIndex:0];
    [enc setTexture:level_view atIndex:1];
    [enc setBuffer:source offset:0 atIndex:2];
    DispatchDxt5(enc, blocks_w, blocks_h);
    [enc endEncoding];
  }
  {
    id<MTLComputeCommandEncoder> enc = [cmd computeCommandEncoder];
    [enc setComputePipelineState:ReadKernel(h.device)];
    [enc setTexture:level_view atIndex:0];
    [enc setBuffer:out offset:kGuardBytes atIndex:0];  // write past prefix guard
    [enc setBytes:dims length:sizeof(dims) atIndex:1];
    [enc dispatchThreadgroups:MTLSizeMake((subw + 7) / 8, (subh + 7) / 8, 1)
        threadsPerThreadgroup:MTLSizeMake(8, 8, 1)];
    [enc endEncoding];
  }
  [cmd commit];
  [cmd waitUntilCompleted];
  if (cmd.status != MTLCommandBufferStatusCompleted) return {};
  RequireGuardsIntact(out, texel_bytes, "dxt5 direct readback");
  const uint8_t* base = static_cast<const uint8_t*>(out.contents) + kGuardBytes;
  return std::vector<uint8_t>(base, base + texel_bytes);
}

id<MTLTexture> MakeMipTexture(id<MTLDevice> device, uint32_t w, uint32_t h,
                              uint32_t levels) {
  MTLTextureDescriptor* d = [MTLTextureDescriptor
      texture2DDescriptorWithPixelFormat:MTLPixelFormatRGBA8Unorm
                                   width:w
                                  height:h
                               mipmapped:(levels > 1)];
  d.mipmapLevelCount = levels;
  d.storageMode = MTLStorageModePrivate;
  d.usage = MTLTextureUsageShaderRead | MTLTextureUsageShaderWrite |
            MTLTextureUsagePixelFormatView;
  return [device newTextureWithDescriptor:d];
}

// Read one RGBA8 word (R low) from a tightly-packed linear RGBA8 buffer.
uint32_t LinearWord(const std::vector<uint8_t>& buf, uint32_t x, uint32_t y,
                    uint32_t pitch_bytes) {
  uint32_t w;
  std::memcpy(&w, &buf[size_t(y) * pitch_bytes + x * 4u], 4);
  return w;
}

TEST_CASE("dxt5 direct: shared decode helper is byte-correct (independent oracle)",
          "[l1][metal][directtex]") {
  // Gate the refactored shared XeDXT5BlockToRGBA8Rows helper (now used by BOTH
  // the linear and direct shaders) against analytically-known outputs that
  // need no interpolation: flat blocks and endpoint-select blocks decode to a
  // known solid color/alpha. Runs the SHARED LINEAR shader (endian kNone so
  // guest bytes == decoded block) over a 8x8 (2x2-block) image of one crafted
  // block and checks every texel.
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  const uint32_t blocks = 2, bw = blocks, bh = blocks;  // 8x8 texels.
  const uint32_t pitch_aligned = 32u;                   // >= bw, 32-aligned.
  // Alpha "all index 1" pattern (3 bits/texel = 0b001 x16) selects a1.
  uint64_t alpha_all1 = 0;
  for (int i = 0; i < 16; ++i) alpha_all1 |= (uint64_t(1) << (3 * i));
  const uint32_t color_all1 = 0x55555555u;  // 2 bits/texel = 01 -> endpoint c1.

  struct Case {
    const char* name;
    std::array<uint8_t, 16> block;
    uint32_t expected;  // solid RGBA8 word every texel must equal.
  };
  std::vector<Case> cases;
  // Flat: c0==c1, a0==a1 -> solid Expand565(c0, a0).
  cases.push_back({"flat mid", MakeDxt5Block(0x40, 0x40, 0, 0x9C79, 0x9C79, 0),
                   Expand565Rgba(0x9C79, 0x40)});
  cases.push_back({"flat white a255",
                   MakeDxt5Block(0xFF, 0xFF, 0, 0xFFFF, 0xFFFF, 0),
                   Expand565Rgba(0xFFFF, 0xFF)});
  cases.push_back({"flat black a0",
                   MakeDxt5Block(0x00, 0x00, 0, 0x0000, 0x0000, 0),
                   Expand565Rgba(0x0000, 0x00)});
  // Color endpoint select (index 0 -> c0, index 1 -> c1), alpha flat.
  cases.push_back({"color idx0 -> c0",
                   MakeDxt5Block(0x80, 0x80, 0, 0x07E0, 0xF81F, 0),
                   Expand565Rgba(0x07E0, 0x80)});
  cases.push_back({"color idx1 -> c1",
                   MakeDxt5Block(0x80, 0x80, 0, 0x07E0, 0xF81F, color_all1),
                   Expand565Rgba(0xF81F, 0x80)});
  // Alpha endpoint select, a0<=a1 => 6-step mode (XeDXT56StepRowToA8), idx0 ->
  // a0, idx1 -> a1; color flat.
  cases.push_back({"alpha 6-step idx0 -> a0",
                   MakeDxt5Block(0x11, 0xEE, 0, 0x1234, 0x1234, 0),
                   Expand565Rgba(0x1234, 0x11)});
  cases.push_back({"alpha 6-step idx1 -> a1",
                   MakeDxt5Block(0x11, 0xEE, alpha_all1, 0x1234, 0x1234, 0),
                   Expand565Rgba(0x1234, 0xEE)});
  // Alpha endpoint select, a0>a1 => 8-step mode (XeDXT58StepRowToA8), the OTHER
  // decode branch — endpoints are still exact at idx0 -> a0, idx1 -> a1.
  cases.push_back({"alpha 8-step idx0 -> a0",
                   MakeDxt5Block(0xEE, 0x11, 0, 0x1234, 0x1234, 0),
                   Expand565Rgba(0x1234, 0xEE)});
  cases.push_back({"alpha 8-step idx1 -> a1",
                   MakeDxt5Block(0xEE, 0x11, alpha_all1, 0x1234, 0x1234, 0),
                   Expand565Rgba(0x1234, 0x11)});

  for (const Case& tc : cases) {
    INFO(tc.name);
    std::vector<uint8_t> src;
    WriteTiledDxt5(src, 0, bw, bh, pitch_aligned,
                   [&](uint32_t, uint32_t) { return tc.block; });
    std::vector<uint8_t> lin =
        RunSharedDxt5Linear(src, 0, pitch_aligned, bw, bh, xenos::Endian::kNone);
    REQUIRE(lin.size() == size_t(SharedLinearPitchBytes(bw)) * (bh * 4u));
    uint32_t pitch_bytes = SharedLinearPitchBytes(bw);
    for (uint32_t y = 0; y < bh * 4u; ++y) {
      for (uint32_t x = 0; x < bw * 4u; ++x) {
        uint32_t w = LinearWord(lin, x, y, pitch_bytes);
        if (w != tc.expected) {
          FAIL("texel (" << x << "," << y << ") = " << std::hex << w
                         << " != expected " << tc.expected);
        }
      }
    }
  }
}

TEST_CASE("dxt5 direct: byte-identical to shared linear shader (varied blocks)",
          "[l1][metal][directtex]") {
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  struct Shape {
    uint32_t w, h;
    xenos::Endian e;
    const char* name;
  };
  const Shape shapes[] = {
      {64, 64, xenos::Endian::kNone, "64x64 none"},
      {64, 64, xenos::Endian::k8in16, "64x64 8in16"},
      {64, 64, xenos::Endian::k8in32, "64x64 8in32"},
      {64, 64, xenos::Endian::k16in32, "64x64 16in32"},
      {20, 12, xenos::Endian::k8in16, "20x12 npot 8in16"},
      {100, 68, xenos::Endian::k8in32, "100x68 npot 8in32"},
      {44, 28, xenos::Endian::k16in32, "44x28 npot 16in32"},
  };
  for (const Shape& s : shapes) {
    INFO(s.name);
    uint32_t bw = (s.w + 3u) / 4u, bh = (s.h + 3u) / 4u;
    uint32_t pitch_aligned = (bw + 31u) & ~31u;
    // Deterministic varied blocks (exercise 6-step/8-step alpha, endpoint
    // orderings, and index spreads across the read set).
    std::vector<uint8_t> src;
    WriteTiledDxt5(src, 0, bw, bh, pitch_aligned, [](uint32_t bx, uint32_t by) {
      uint32_t s = bx * 2654435761u + by * 40503u + 1u;
      std::array<uint8_t, 16> b{};
      for (int i = 0; i < 16; ++i) {
        s = s * 1664525u + 1013904223u;
        b[i] = uint8_t(s >> 24);
      }
      return b;
    });
    std::vector<uint8_t> lin =
        RunSharedDxt5Linear(src, 0, pitch_aligned, bw, bh, s.e);
    REQUIRE(!lin.empty());
    id<MTLTexture> tex = MakeMipTexture(H().device, s.w, s.h, 1);
    std::vector<uint8_t> direct =
        RunDirectDxt5(src, 0, pitch_aligned, s.w, s.h, 0, 0, s.e, tex, 0);
    REQUIRE(direct.size() == size_t(s.w) * s.h * 4u);
    // Compare the direct sub-image against the shared linear output texel-wise
    // (the linear extent covers full blocks; the direct texture is exact size).
    uint32_t pitch_bytes = SharedLinearPitchBytes(bw);
    for (uint32_t y = 0; y < s.h; ++y) {
      for (uint32_t x = 0; x < s.w; ++x) {
        uint32_t dw;
        std::memcpy(&dw, &direct[(size_t(y) * s.w + x) * 4u], 4);
        uint32_t lw = LinearWord(lin, x, y, pitch_bytes);
        if (dw != lw) {
          FAIL("texel (" << x << "," << y << ") direct " << std::hex << dw
                         << " != shared " << lw);
        }
      }
    }
    // Repeat determinism.
    std::vector<uint8_t> direct2 =
        RunDirectDxt5(src, 0, pitch_aligned, s.w, s.h, 0, 0, s.e, tex, 0);
    REQUIRE(direct2 == direct);
  }
}

TEST_CASE("dxt5 direct: mip chain + packed tail byte-identical to shared linear",
          "[l1][metal][directtex]") {
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  struct Shape {
    uint32_t w, h, max_level;
    xenos::Endian e;
    const char* name;
  };
  const Shape shapes[] = {
      {256, 256, 8, xenos::Endian::k8in16, "256x256 pow2"},
      {96, 64, 6, xenos::Endian::k8in32, "96x64 npot"},
  };
  for (const Shape& s : shapes) {
    INFO(s.name);
    uint32_t pitch_div32 = ((s.w + 31u) & ~31u) >> 5;
    texture_util::TextureGuestLayout layout =
        texture_util::GetGuestTextureLayout(
            xenos::DataDimension::k2DOrStacked, pitch_div32, s.w, s.h, 1,
            /*tiled=*/true, xenos::TextureFormat::k_DXT4_5,
            /*has_packed_levels=*/true, /*has_base=*/true, s.max_level);
    uint32_t packed = layout.packed_level;

    // One guest buffer: base region at 0, mip region after it (block-tiled).
    // Fill deterministically over the whole thing; both shaders read the same
    // bytes at identical addresses.
    // Size generously to cover every level's tiled read set.
    uint32_t block_w0 = (s.w + 3u) / 4u, block_h0 = (s.h + 3u) / 4u;
    uint32_t base_pitch = ((block_w0 + 31u) & ~31u);
    uint32_t base_end = 0;
    {
      std::vector<uint8_t> tmp;
      WriteTiledDxt5(tmp, 0, block_w0, block_h0, base_pitch,
                     [](uint32_t, uint32_t) { return std::array<uint8_t, 16>{}; });
      base_end = uint32_t(tmp.size());
    }
    uint32_t mip_region =
        xe::align(base_end, xenos::kTextureSubresourceAlignmentBytes);
    // Determine the full buffer size by probing every level's read set.
    auto level_plan = [&](uint32_t level, uint32_t& guest_off,
                          uint32_t& pitch_blk, uint32_t& lw, uint32_t& lh,
                          uint32_t& ext_bw, uint32_t& ext_bh, uint32_t& px,
                          uint32_t& py) {
      bool is_base = level == 0;
      uint32_t store = std::min(level, packed);
      const texture_util::TextureGuestLayout::Level& lvl =
          is_base ? layout.base : layout.mips[store];
      pitch_blk = lvl.row_pitch_bytes / kDxtBpb;
      lw = std::max(s.w >> level, 1u);
      lh = std::max(s.h >> level, 1u);
      guest_off = is_base ? 0u : (mip_region + layout.mip_offsets_bytes[store]);
      px = py = 0;
      if (packed != UINT32_MAX && level >= packed) {
        uint32_t pz;
        texture_util::GetPackedMipOffset(s.w, s.h, 1,
                                         xenos::TextureFormat::k_DXT4_5, level,
                                         px, py, pz);
        ext_bw = lvl.x_extent_blocks;
        ext_bh = lvl.y_extent_blocks;
      } else {
        ext_bw = (lw + 3u) / 4u;
        ext_bh = (lh + 3u) / 4u;
      }
    };

    // Build the source buffer sized to the max read end across levels.
    std::vector<uint8_t> src;
    auto fill_block = [](uint32_t bx, uint32_t by) {
      uint32_t s2 = bx * 374761393u + by * 668265263u + 7u;
      std::array<uint8_t, 16> b{};
      for (int i = 0; i < 16; ++i) {
        s2 = s2 * 1664525u + 1013904223u;
        b[i] = uint8_t(s2 >> 24);
      }
      return b;
    };
    for (uint32_t level = 0; level <= s.max_level; ++level) {
      uint32_t go, pb, lw, lh, ebw, ebh, px, py;
      level_plan(level, go, pb, lw, lh, ebw, ebh, px, py);
      // Write the extent the shared shader will read (covers packed tail).
      WriteTiledDxt5(src, go, ebw, ebh, pb, fill_block);
    }

    id<MTLTexture> tex = MakeMipTexture(H().device, s.w, s.h, s.max_level + 1);
    uint32_t packed_nonzero = 0;
    for (uint32_t level = 0; level <= s.max_level; ++level) {
      uint32_t go, pb, lw, lh, ebw, ebh, px, py;
      level_plan(level, go, pb, lw, lh, ebw, ebh, px, py);
      INFO("level " << level << " " << lw << "x" << lh << " px " << px << " py "
                    << py);
      if (px != 0 || py != 0) ++packed_nonzero;
      // Reference: shared linear over the extent (tail or level).
      std::vector<uint8_t> lin =
          RunSharedDxt5Linear(src, go, pb, ebw, ebh, s.e);
      REQUIRE(!lin.empty());
      uint32_t ext_pitch = SharedLinearPitchBytes(ebw);
      // Direct: sub-mip via a level-scoped view, packed offset applied.
      std::vector<uint8_t> direct =
          RunDirectDxt5(src, go, pb, lw, lh, px, py, s.e, tex, level);
      REQUIRE(direct.size() == size_t(lw) * lh * 4u);
      for (uint32_t y = 0; y < lh; ++y) {
        for (uint32_t x = 0; x < lw; ++x) {
          uint32_t dw;
          std::memcpy(&dw, &direct[(size_t(y) * lw + x) * 4u], 4);
          uint32_t lw2 = LinearWord(lin, px * 4u + x, py * 4u + y, ext_pitch);
          if (dw != lw2) {
            FAIL("level " << level << " texel (" << x << "," << y << ") direct "
                          << std::hex << dw << " != shared " << lw2);
          }
        }
      }
    }
    // The chain must actually exercise packed sub-mips at nonzero offsets.
    REQUIRE(packed_nonzero >= 1u);
  }
}

TEST_CASE("dxt5 direct: filtered-sampling parity with shared buffer+blit",
          "[l1][metal][directtex]") {
  REQUIRE_DEVICE();
  REQUIRE(H().ok);
  const uint32_t w = 64, h = 64;
  const xenos::Endian e = xenos::Endian::k8in16;
  uint32_t bw = w / 4u, bh = h / 4u;
  uint32_t pitch_aligned = (bw + 31u) & ~31u;
  std::vector<uint8_t> src;
  WriteTiledDxt5(src, 0, bw, bh, pitch_aligned, [](uint32_t bx, uint32_t by) {
    uint32_t s = bx * 2246822519u + by * 3266489917u + 3u;
    std::array<uint8_t, 16> b{};
    for (int i = 0; i < 16; ++i) {
      s = s * 1664525u + 1013904223u;
      b[i] = uint8_t(s >> 24);
    }
    return b;
  });
  // Direct texture.
  id<MTLTexture> dtex = MakeMipTexture(H().device, w, h, 1);
  (void)RunDirectDxt5(src, 0, pitch_aligned, w, h, 0, 0, e, dtex, 0);
  // Shared buffer+blit texture: shared linear -> blit into an RGBA8 texture.
  std::vector<uint8_t> lin = RunSharedDxt5Linear(src, 0, pitch_aligned, bw, bh, e);
  uint32_t host_pitch = SharedLinearPitchBytes(bw);
  id<MTLTexture> btex = MakeTexture(H().device, w, h, false);
  {
    id<MTLBuffer> linear = [H().device newBufferWithBytes:lin.data()
                                                   length:lin.size()
                                                  options:MTLResourceStorageModeShared];
    id<MTLCommandBuffer> cmd = [H().queue commandBuffer];
    id<MTLBlitCommandEncoder> blit = [cmd blitCommandEncoder];
    [blit copyFromBuffer:linear
             sourceOffset:0
        sourceBytesPerRow:host_pitch
      sourceBytesPerImage:host_pitch * h
               sourceSize:MTLSizeMake(w, h, 1)
                toTexture:btex
         destinationSlice:0
         destinationLevel:0
        destinationOrigin:MTLOriginMake(0, 0, 0)];
    [blit endEncoding];
    [cmd commit];
    [cmd waitUntilCompleted];
  }
  std::vector<simd_float2> coords;
  for (uint32_t gy = 0; gy <= 6; ++gy) {
    for (uint32_t gx = 0; gx <= 6; ++gx) {
      coords.push_back(simd_make_float2((float(gx) / 6.0f) + 0.25f / float(w),
                                        (float(gy) / 6.0f) + 0.25f / float(h)));
    }
  }
  for (float ec : {0.0f, 1.0f}) {
    coords.push_back(simd_make_float2(ec, 0.5f));
    coords.push_back(simd_make_float2(0.5f, ec));
  }
  std::vector<simd_float4> ds = SampleAt(dtex, coords);
  std::vector<simd_float4> bs = SampleAt(btex, coords);
  REQUIRE(ds.size() == coords.size());
  REQUIRE(bs.size() == coords.size());
  for (size_t i = 0; i < coords.size(); ++i) {
    for (int cc = 0; cc < 4; ++cc) {
      if (ds[i][cc] != bs[i][cc]) {
        FAIL("coord " << i << " ch " << cc << " direct " << ds[i][cc]
                      << " != buffer+blit " << bs[i][cc]);
      }
    }
  }
}

