    }
  }
}

TEST_CASE("direct texture load: packed tail places sub-mips at nonzero offsets",
          "[l1][metal][directtex]") {
  // Device-free structural proof that the mip-chain byte case above genuinely
  // exercises the decoupled source-read path: the 256x256 chain has a packed
  // tail spanning multiple levels, at least one at a nonzero (px,py) sub-tile
