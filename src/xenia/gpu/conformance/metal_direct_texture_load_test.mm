// L1 (on-device): C1T G0 — the direct-to-tiled-texture compute load. The
// narrow RGBA8 variant (texture_load_32bpb_direct.cs.xesl) reuses the shared
// texture_load source/endian/address logic and writes an ordinary
// optimally-tiled RGBA8Unorm MTLTexture directly, with no linear staging
// buffer and no staging->texture blit. These cases prove functional
// byte-identity (G0b) against BOTH the production CPU oracle and the existing
// buffer+blit shape, and are device-REQUIRED (fail, never skip). The G0c
// sampling/mechanism cost measurement is NOT gated here as a flaky wall-clock
// test — it is run and recorded in
// docs/metal_texture_cache_integration_adr.md "C1T G0 outcome".

