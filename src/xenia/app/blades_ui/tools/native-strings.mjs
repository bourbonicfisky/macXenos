// The app's own menus, About panel, alert titles and open-panel titles in
// each language: the catalogs' "native.*" messages, written as the
// Localizable.strings the native code reads through NSLocalizedString.
// One source for both: src/i18n/en.ts and src/i18n/catalogs/<code>.ts.
//
//   node tools/native-strings.mjs           write them (npm run build does)
//   node tools/native-strings.mjs --check   exit 1 if they are stale
//
// Writes ../localization/<code>.lproj/Localizable.strings (beside the app's
// sources), which package_mac.sh copies into Contents/Resources and the
// CMake build copies beside the binary. The key is the English text, as
// NSLocalizedString(@"Hide Others", …) looks it up; a {placeholder} is %@
// (%1$@, %2$@… when there are several), and a message with one escapes a
// literal % as %%. A message a catalog lacks is left out, so the English key
// shows.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const NATIVE_DIR = join(ROOT, "..", "localization");
const PREFIX = "native.";
// The .lproj a catalog is written as, where Apple's name differs: pt.lproj
// is Brazilian Portuguese in Apple's own apps, and a Mac set to Portugal's
// (pt-PT) falls back to it too.
const LPROJ = { "pt-BR": "pt" };

/** "About {app}" -> "About %@"; the names in English's order. */
export function toFormat(message, order) {
  const names = order ?? [...message.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
  if (!names.length) return message;
  const escaped = message.replace(/%/g, "%%");
  return escaped.replace(/\{(\w+)\}/g, (_, name) =>
    names.length === 1 ? "%@" : `%${names.indexOf(name) + 1}$@`
  );
}

const quote = (text) =>
  `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/\t/g, "\\t")}"`;

/** The English key a native message is looked up by. */
export function nativeKey(english) {
  return toFormat(english);
}

/** { "<code>.lproj/Localizable.strings": text } for English and each catalog. */
export async function nativeTables() {
  const { en } = await import(join(ROOT, "src", "i18n", "en.ts"));
  const keys = Object.keys(en).filter((key) => key.startsWith(PREFIX));
  const catalogDir = join(ROOT, "src", "i18n", "catalogs");
  const codes = ["en", ...readdirSync(catalogDir).filter((f) => f.endsWith(".ts")).map((f) => f.slice(0, -3)).sort()];
  const tables = {};
  for (const code of codes) {
    const catalog = code === "en" ? en : (await import(join(catalogDir, `${code}.ts`))).default;
    const lines = [
      "/* Generated by src/xenia/app/blades_ui/tools/native-strings.mjs from",
      `   src/i18n/${code === "en" ? "en.ts" : `catalogs/${code}.ts`} (npm run build). Do not edit: change the catalog. */`,
      ""
    ];
    for (const key of keys) {
      const text = catalog[key];
      if (typeof text !== "string" || !text.trim()) continue;
      const order = [...en[key].matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
      lines.push(`/* ${key} */`);
      lines.push(`${quote(nativeKey(en[key]))} = ${quote(toFormat(text, order))};`);
      lines.push("");
    }
    tables[`${LPROJ[code] ?? code}.lproj/Localizable.strings`] = lines.join("\n");
  }
  return tables;
}

/** The tables on disk that differ from, or are missing from, what the
    catalogs give now, and any left over from a removed language. */
export async function staleTables() {
  const tables = await nativeTables();
  const stale = Object.entries(tables)
    .filter(([path, text]) => !existsSync(join(NATIVE_DIR, path)) || readFileSync(join(NATIVE_DIR, path), "utf8") !== text)
    .map(([path]) => path);
  if (existsSync(NATIVE_DIR)) {
    for (const dir of readdirSync(NATIVE_DIR)) {
      if (dir.endsWith(".lproj") && !(`${dir}/Localizable.strings` in tables)) stale.push(dir);
    }
  }
  return stale;
}

export async function writeTables() {
  const tables = await nativeTables();
  if (existsSync(NATIVE_DIR)) {
    for (const dir of readdirSync(NATIVE_DIR)) {
      if (dir.endsWith(".lproj") && !(`${dir}/Localizable.strings` in tables)) rmSync(join(NATIVE_DIR, dir), { recursive: true });
    }
  }
  for (const [path, text] of Object.entries(tables)) {
    mkdirSync(dirname(join(NATIVE_DIR, path)), { recursive: true });
    writeFileSync(join(NATIVE_DIR, path), text);
  }
  return Object.keys(tables);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes("--check")) {
    const stale = await staleTables();
    if (stale.length) {
      console.log(`stale: ${stale.join(", ")}. Run npm run build.`);
      process.exit(1);
    }
  } else {
    const written = await writeTables();
    console.log(`Wrote ${written.length} Localizable.strings to src/xenia/app/localization/`);
  }
}
