namespace {

// immediate.vs.xesl declares push_const_binding_xe(buffer(0)), so vertex
// attribute data binds at buffer(1). immediate.ps.xesl declares its sampler at
// texture(0)/sampler(0).
constexpr NSUInteger kPushConstantBufferIndex = 0;
constexpr NSUInteger kVertexBufferIndex = 1;
constexpr NSUInteger kFragmentTextureIndex = 0;
constexpr NSUInteger kFragmentSamplerIndex = 0;

// The presenter's drawable format. Must match
// MetalPresenter's CAMetalLayer pixel format or pipeline creation fails.
constexpr MTLPixelFormat kDrawablePixelFormat = MTLPixelFormatBGRA8Unorm;

id<MTLFunction> LoadFunction(id<MTLDevice> device, const uint8_t* metallib,
                             size_t size, const char* name) {
  dispatch_data_t data = dispatch_data_create(metallib, size, nullptr, ^{
  });
  NSError* error = nil;
  id<MTLLibrary> library = [device newLibraryWithData:data error:&error];
  if (!library) {
    XELOGE("MetalImmediateDrawer: newLibraryWithData failed for {}: {}", name,
           error ? [[error localizedDescription] UTF8String] : "unknown");
    return nil;
  }
  // The XeSL MSL entry point is always entry_xe; resolve by name rather than
  // trusting function order.
  id<MTLFunction> function = [library newFunctionWithName:@"entry_xe"];
  if (!function) {
    XELOGE("MetalImmediateDrawer: no entry_xe in {}", name);
  }
  return function;
}

}  // namespace

MetalImmediateDrawer::~MetalImmediateDrawer() { Shutdown(); }

MetalImmediateDrawer::MetalImmediateTexture::~MetalImmediateTexture() {
  if (texture) {
    CFBridgingRelease(texture);
    texture = nullptr;
  }
  if (sampler) {
    CFBridgingRelease(sampler);
    sampler = nullptr;
  }
}

bool MetalImmediateDrawer::Initialize(void* device) {
  assert_not_null(device);
  device_ = device;
  id<MTLDevice> mtl_device = (__bridge id<MTLDevice>)device;

  @autoreleasepool {
    // 1x1 white texture so untextured draws can share the single textured
    // pipeline: sampling white leaves the vertex color unchanged.
    MTLTextureDescriptor* white_desc = [MTLTextureDescriptor
        texture2DDescriptorWithPixelFormat:MTLPixelFormatRGBA8Unorm
                                     width:1
                                    height:1
                                 mipmapped:NO];
    white_desc.usage = MTLTextureUsageShaderRead;
    white_desc.storageMode = MTLStorageModeShared;
    id<MTLTexture> white = [mtl_device newTextureWithDescriptor:white_desc];
    if (!white) {
      XELOGE("MetalImmediateDrawer: failed to create the white texture");
      return false;
    }
    const uint32_t white_pixel = 0xFFFFFFFFu;
    [white replaceRegion:MTLRegionMake2D(0, 0, 1, 1)
             mipmapLevel:0
               withBytes:&white_pixel
             bytesPerRow:4];
    white_texture_ = (void*)CFBridgingRetain(white);

    MTLSamplerDescriptor* sampler_desc = [[MTLSamplerDescriptor alloc] init];
    sampler_desc.minFilter = MTLSamplerMinMagFilterLinear;
    sampler_desc.magFilter = MTLSamplerMinMagFilterLinear;
    sampler_desc.sAddressMode = MTLSamplerAddressModeClampToEdge;
    sampler_desc.tAddressMode = MTLSamplerAddressModeClampToEdge;
    id<MTLSamplerState> sampler =
        [mtl_device newSamplerStateWithDescriptor:sampler_desc];
    if (!sampler) {
      XELOGE("MetalImmediateDrawer: failed to create the default sampler");
      Shutdown();
      return false;
    }
    default_sampler_ = (void*)CFBridgingRetain(sampler);

    id<MTLFunction> vs = LoadFunction(mtl_device, immediate_vs_metallib,
                                      sizeof(immediate_vs_metallib),
                                      "immediate_vs");
    if (!vs) {
      Shutdown();
      return false;
    }
    id<MTLFunction> ps = LoadFunction(mtl_device, immediate_ps_metallib,
                                      sizeof(immediate_ps_metallib),
                                      "immediate_ps");
    if (!ps) {
      Shutdown();
      return false;
    }

    // ImmediateVertex is {float x, y; float u, v; uint32_t color;} and the
    // shader takes color as float4, so the packed RGBA8 unpacks through the
    // vertex format rather than in the shader.
    MTLVertexDescriptor* vertex_desc = [[MTLVertexDescriptor alloc] init];
    vertex_desc.attributes[0].format = MTLVertexFormatFloat2;
    vertex_desc.attributes[0].offset = offsetof(ImmediateVertex, x);
    vertex_desc.attributes[0].bufferIndex = kVertexBufferIndex;
    vertex_desc.attributes[1].format = MTLVertexFormatFloat2;
    vertex_desc.attributes[1].offset = offsetof(ImmediateVertex, u);
    vertex_desc.attributes[1].bufferIndex = kVertexBufferIndex;
    vertex_desc.attributes[2].format = MTLVertexFormatUChar4Normalized;
    vertex_desc.attributes[2].offset = offsetof(ImmediateVertex, color);
    vertex_desc.attributes[2].bufferIndex = kVertexBufferIndex;
    vertex_desc.layouts[kVertexBufferIndex].stride = sizeof(ImmediateVertex);
    vertex_desc.layouts[kVertexBufferIndex].stepRate = 1;
    vertex_desc.layouts[kVertexBufferIndex].stepFunction =
        MTLVertexStepFunctionPerVertex;

    MTLRenderPipelineDescriptor* pipeline_desc =
        [[MTLRenderPipelineDescriptor alloc] init];
    pipeline_desc.label = @"xe immediate overlay";
    pipeline_desc.vertexFunction = vs;
    pipeline_desc.fragmentFunction = ps;
    pipeline_desc.vertexDescriptor = vertex_desc;
    MTLRenderPipelineColorAttachmentDescriptor* color =
        pipeline_desc.colorAttachments[0];
    color.pixelFormat = kDrawablePixelFormat;
    // Straight (non-premultiplied) alpha, matching what ImGui emits.
    color.blendingEnabled = YES;
    color.rgbBlendOperation = MTLBlendOperationAdd;
    color.alphaBlendOperation = MTLBlendOperationAdd;
    color.sourceRGBBlendFactor = MTLBlendFactorSourceAlpha;
    color.sourceAlphaBlendFactor = MTLBlendFactorSourceAlpha;
    color.destinationRGBBlendFactor = MTLBlendFactorOneMinusSourceAlpha;
    color.destinationAlphaBlendFactor = MTLBlendFactorOneMinusSourceAlpha;

    NSError* error = nil;
    id<MTLRenderPipelineState> pipeline =
        [mtl_device newRenderPipelineStateWithDescriptor:pipeline_desc
                                                   error:&error];
    if (!pipeline) {
      XELOGE("MetalImmediateDrawer: failed to create the overlay pipeline: {}",
             error ? [[error localizedDescription] UTF8String] : "unknown");
      Shutdown();
      return false;
    }
    pipeline_ = (void*)CFBridgingRetain(pipeline);
  }

  XELOGI("MetalImmediateDrawer: initialized");
  return true;
}

void MetalImmediateDrawer::Shutdown() {
  if (current_vertex_buffer_) {
    CFBridgingRelease(current_vertex_buffer_);
    current_vertex_buffer_ = nullptr;
  }
  if (current_index_buffer_) {
    CFBridgingRelease(current_index_buffer_);
    current_index_buffer_ = nullptr;
  }
  if (pipeline_) {
    CFBridgingRelease(pipeline_);
    pipeline_ = nullptr;
  }
  if (white_texture_) {
    CFBridgingRelease(white_texture_);
    white_texture_ = nullptr;
  }
  if (default_sampler_) {
    CFBridgingRelease(default_sampler_);
    default_sampler_ = nullptr;
  }
  current_render_encoder_ = nullptr;
  batch_open_ = false;
}

std::unique_ptr<ImmediateTexture> MetalImmediateDrawer::CreateTexture(
    uint32_t width, uint32_t height, ImmediateTextureFilter filter,
    bool is_repeated, const uint8_t* data) {
  if (!device_ || !width || !height) {
    return nullptr;
  }
  id<MTLDevice> mtl_device = (__bridge id<MTLDevice>)device_;

  auto texture = std::make_unique<MetalImmediateTexture>(width, height);

  @autoreleasepool {
    MTLTextureDescriptor* desc = [MTLTextureDescriptor
        texture2DDescriptorWithPixelFormat:MTLPixelFormatRGBA8Unorm
                                     width:width
                                    height:height
                                 mipmapped:NO];
    desc.usage = MTLTextureUsageShaderRead;
    // Shared rather than Managed: Apple Silicon is unified-memory, and this
    // avoids a didModifyRange round trip for the font atlas upload.
    desc.storageMode = MTLStorageModeShared;
    id<MTLTexture> mtl_texture = [mtl_device newTextureWithDescriptor:desc];
    if (!mtl_texture) {
      XELOGE("MetalImmediateDrawer: failed to create a {}x{} texture", width,
             height);
      return nullptr;
    }
    if (data) {
      [mtl_texture replaceRegion:MTLRegionMake2D(0, 0, width, height)
                     mipmapLevel:0
                       withBytes:data
                     bytesPerRow:size_t(width) * 4];
    }
    texture->texture = (void*)CFBridgingRetain(mtl_texture);

    MTLSamplerDescriptor* sampler_desc = [[MTLSamplerDescriptor alloc] init];
    MTLSamplerMinMagFilter mag_min =
        filter == ImmediateTextureFilter::kLinear
            ? MTLSamplerMinMagFilterLinear
            : MTLSamplerMinMagFilterNearest;
    sampler_desc.minFilter = mag_min;
    sampler_desc.magFilter = mag_min;
    MTLSamplerAddressMode address_mode = is_repeated
                                             ? MTLSamplerAddressModeRepeat
                                             : MTLSamplerAddressModeClampToEdge;
    sampler_desc.sAddressMode = address_mode;
    sampler_desc.tAddressMode = address_mode;
    id<MTLSamplerState> sampler =
        [mtl_device newSamplerStateWithDescriptor:sampler_desc];
    if (!sampler) {
      XELOGE("MetalImmediateDrawer: failed to create a sampler");
      return nullptr;
    }
    texture->sampler = (void*)CFBridgingRetain(sampler);
  }

  return texture;
}

void MetalImmediateDrawer::Begin(UIDrawContext& ui_draw_context,
                                 float coordinate_space_width,
                                 float coordinate_space_height) {
  ImmediateDrawer::Begin(ui_draw_context, coordinate_space_width,
                         coordinate_space_height);

  auto& metal_context = static_cast<MetalUIDrawContext&>(ui_draw_context);
  current_render_encoder_ = metal_context.render_encoder();
  if (!current_render_encoder_ || !pipeline_) {
    return;
  }

  id<MTLRenderCommandEncoder> encoder =
      (__bridge id<MTLRenderCommandEncoder>)current_render_encoder_;

  // The encoder is shared with the guest-output blit, which set its own
  // viewport/scissor; reset both to the full render target so overlay draws
  // start from a known state.
  uint32_t rt_width = metal_context.render_target_width();
  uint32_t rt_height = metal_context.render_target_height();
  MTLViewport viewport;
  viewport.originX = 0.0;
  viewport.originY = 0.0;
  viewport.width = double(rt_width);
  viewport.height = double(rt_height);
  viewport.znear = 0.0;
  viewport.zfar = 1.0;
  [encoder setViewport:viewport];
  MTLScissorRect scissor;
  scissor.x = 0;
  scissor.y = 0;
  scissor.width = rt_width;
  scissor.height = rt_height;
  [encoder setScissorRect:scissor];

  // immediate.vs.xesl push constant: float2 xe_coordinate_space_size_inv.
  // Guard against a zero coordinate space, which would produce infinities.
  float coordinate_space_size_inv[2] = {
      coordinate_space_width > 0.0f ? 1.0f / coordinate_space_width : 0.0f,
      coordinate_space_height > 0.0f ? 1.0f / coordinate_space_height : 0.0f,
  };
  [encoder setVertexBytes:coordinate_space_size_inv
                   length:sizeof(coordinate_space_size_inv)
                  atIndex:kPushConstantBufferIndex];
}

void MetalImmediateDrawer::BeginDrawBatch(const ImmediateDrawBatch& batch) {
  assert_false(batch_open_);
  batch_open_ = true;
  if (!current_render_encoder_ || !device_ || !batch.vertices ||
      batch.vertex_count <= 0) {
    return;
  }
  id<MTLDevice> mtl_device = (__bridge id<MTLDevice>)device_;
  id<MTLRenderCommandEncoder> encoder =
      (__bridge id<MTLRenderCommandEncoder>)current_render_encoder_;

  @autoreleasepool {
    id<MTLBuffer> vertex_buffer = [mtl_device
        newBufferWithBytes:batch.vertices
                    length:size_t(batch.vertex_count) * sizeof(ImmediateVertex)
                   options:MTLResourceStorageModeShared];
    if (!vertex_buffer) {
      XELOGE("MetalImmediateDrawer: failed to allocate {} vertices",
             batch.vertex_count);
      return;
    }
    current_vertex_buffer_ = (void*)CFBridgingRetain(vertex_buffer);
    [encoder setVertexBuffer:vertex_buffer
                      offset:0
                     atIndex:kVertexBufferIndex];

    if (batch.indices && batch.index_count > 0) {
      id<MTLBuffer> index_buffer = [mtl_device
          newBufferWithBytes:batch.indices
                      length:size_t(batch.index_count) * sizeof(uint16_t)
                     options:MTLResourceStorageModeShared];
      if (!index_buffer) {
        XELOGE("MetalImmediateDrawer: failed to allocate {} indices",
               batch.index_count);
        return;
      }
      current_index_buffer_ = (void*)CFBridgingRetain(index_buffer);
    }
  }
}

void MetalImmediateDrawer::Draw(const ImmediateDraw& draw) {
  assert_true(batch_open_);
  if (!current_render_encoder_ || !pipeline_ || !current_vertex_buffer_ ||
      draw.count <= 0) {
    return;
  }

  // Returns false when the scissor selects no render-target pixels, which
  // covers the degenerate right < left / bottom < top case. For a draw with
  // scissor disabled the helper writes the full render target, so scissor state
  // can never leak from a previous draw.
  uint32_t scissor_left, scissor_top, scissor_width, scissor_height;
  if (!ScissorToRenderTarget(draw, scissor_left, scissor_top, scissor_width,
                             scissor_height)) {
    return;
  }

  id<MTLRenderCommandEncoder> encoder =
      (__bridge id<MTLRenderCommandEncoder>)current_render_encoder_;

  [encoder setRenderPipelineState:(__bridge id<MTLRenderPipelineState>)
                                      pipeline_];

  MTLScissorRect scissor;
  scissor.x = scissor_left;
  scissor.y = scissor_top;
  scissor.width = scissor_width;
  scissor.height = scissor_height;
  [encoder setScissorRect:scissor];

  // A null texture draws with vertex color only, achieved by sampling the 1x1
  // white texture through the same pipeline.
  void* texture_ptr = white_texture_;
  void* sampler_ptr = default_sampler_;
  if (draw.texture) {
    auto* metal_texture = static_cast<MetalImmediateTexture*>(draw.texture);
    if (metal_texture->texture) {
      texture_ptr = metal_texture->texture;
      sampler_ptr = metal_texture->sampler ? metal_texture->sampler
                                           : default_sampler_;
    }
  }
  [encoder setFragmentTexture:(__bridge id<MTLTexture>)texture_ptr
                      atIndex:kFragmentTextureIndex];
  if (sampler_ptr) {
    [encoder setFragmentSamplerState:(__bridge id<MTLSamplerState>)sampler_ptr
                             atIndex:kFragmentSamplerIndex];
  }

  MTLPrimitiveType primitive_type =
      draw.primitive_type == ImmediatePrimitiveType::kTriangles
          ? MTLPrimitiveTypeTriangle
          : MTLPrimitiveTypeLine;

  if (current_index_buffer_) {
    id<MTLBuffer> index_buffer =
        (__bridge id<MTLBuffer>)current_index_buffer_;
    [encoder drawIndexedPrimitives:primitive_type
                        indexCount:NSUInteger(draw.count)
                         indexType:MTLIndexTypeUInt16
                       indexBuffer:index_buffer
                 indexBufferOffset:size_t(draw.index_offset) * sizeof(uint16_t)
                     instanceCount:1
                        baseVertex:draw.base_vertex
                      baseInstance:0];
  } else {
    [encoder drawPrimitives:primitive_type
                vertexStart:NSUInteger(draw.base_vertex)
                vertexCount:NSUInteger(draw.count)];
  }
}

void MetalImmediateDrawer::EndDrawBatch() {
  assert_true(batch_open_);
  batch_open_ = false;
  // Safe to release now even though the GPU has not run: the command buffer
  // retains every resource its encoders reference until completion.
  if (current_vertex_buffer_) {
    CFBridgingRelease(current_vertex_buffer_);
    current_vertex_buffer_ = nullptr;
  }
  if (current_index_buffer_) {
    CFBridgingRelease(current_index_buffer_);
    current_index_buffer_ = nullptr;
  }
}

void MetalImmediateDrawer::End() { current_render_encoder_ = nullptr; }

