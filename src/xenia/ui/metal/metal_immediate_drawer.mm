// Generated by xe_shader_rules_metal from the shared polyglot XeSL sources
// (src/xenia/ui/shaders/immediate.{vs,ps}.xesl), same rule and compiler the GPU
// texture-load shaders use.
#include "xenia/ui/shaders/bytecode/metal/immediate_ps.h"
#include "xenia/ui/shaders/bytecode/metal/immediate_vs.h"

#import <Metal/Metal.h>

namespace xe {
